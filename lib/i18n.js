/** Наш код языка из тега системы: pt-BR → pt, zh-Hans-CN → zh, in → id. */
function base(tag) {
  const c = String(tag || '').toLowerCase().split(/[-_]/)[0];
  return c === 'in' ? 'id' : c;
}

/** Язык системы, если он у нас есть, иначе английский. */
export function systemLang() {
  let tag = '';
  try { tag = self.chrome?.i18n?.getUILanguage?.() || ''; } catch { /* не расширение */ }
  const c = base(tag || navigator.language);
  return UI_LANGS.includes(c) ? c : 'en';
}

const stored = () => { try { return localStorage.getItem('uiLang') || ''; } catch { return ''; } };
let cur = UI_LANGS.includes(stored()) ? stored() : systemLang();
const subs = new Set();

/** Текущий язык интерфейса. */
export const uiLang = () => cur;

/**
 * Надпись по ключу; {a}, {b} — подстановки. Нет перевода — английская: новый
 * ключ, добавленный только в en, не оставит кнопку пустой.
 */
export function t(key, vars) {
  const d = D[cur], e = D.en, k = key + '@app';
  let s = (APP ? d[k] ?? d[key] ?? e[k] : d[key]) ?? e[key] ?? key;
  if (vars) s = s.replace(/\{(\w)\}/g, (m, k) => vars[k] ?? m);
  return s;
}

/** Статичные надписи разметки: data-i18n (текст), data-i18n-aria, data-i18n-title. */
export function localize(root = document) {
  document.documentElement.lang = cur;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
}

/** Позвать fn при смене языка (в этой странице или в другой). */
export function onUiLang(fn) { subs.add(fn); }

function use(code) {
  const c = UI_LANGS.includes(code) ? code : systemLang();
  if (c === cur) return;
  cur = c;
  for (const fn of subs) fn(c);
}

/** Выбор зрителя: запомнить в хранилище, остальные страницы узнают по onChanged. */
export function setUiLang(code) {
  try { localStorage.setItem('uiLang', code); } catch { /* без localStorage — только хранилище */ }
  use(code);
  self.chrome?.storage?.local?.set({ uiLang: code }).catch(() => {});
}

// Хранилище главнее копии: её могло не быть (другой профиль, очищено).
self.chrome?.storage?.local?.get('uiLang').then((o) => {
  if (!o?.uiLang) return;
  try { localStorage.setItem('uiLang', o.uiLang); } catch { /* только память */ }
  use(o.uiLang);
}).catch(() => {});
self.chrome?.storage?.onChanged?.addListener((ch, area) => {
  if (area !== 'local' || !ch.uiLang) return;
  try { localStorage.setItem('uiLang', ch.uiLang.newValue || ''); } catch { /* только память */ }
  use(ch.uiLang.newValue || '');
});
