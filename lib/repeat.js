// Зацикленный повтор: модель упёрлась в лимит токенов и печатает одно и то же.
//
// Так ломаются обе модели, и это не редкость. На трёхминутном ролике четыре
// реплики из сорока пяти выглядели так:
//
//   …almost $10 million to the big, big, big, big, big, ×24
//   …pretty fast in this video which is why it is why it is why it ×17
//   …how many kids go to school in here? 325. 320. 320. 320. ×13
//   …okay we gotta win no we gotta win we gotta win we gotta win
//
// Потолок на длину ответа (genFor в lib/models.js) обрывает такую строку, но
// не убирает её: до потолка помещается два десятка повторов, и они занимают
// весь экран, весь перевод и всю расшифровку. Настоящих слов в куске при этом
// распознано пять, а посчитается он как сорок.
//
// Лечится после генерации и по тексту: подряд идущие одинаковые куски слов —
// это почти всегда сбой декодера. Почти — потому что человек повторяется тоже,
// и отличить одно от другого надо, не полагаясь на вкус. Отличаем по замеру:
// в ручной расшифровке того же ролика (3711 слов) все повторы от трёх раз и
// выше — односложные возгласы, «yes yes yes», «cheers cheers cheers», «wow»
// четырежды. Повтора из двух и более слов подряд трижды у человека нет ни
// одного, а у модели такие есть: «by the end of the video» ×3, «it gets backed
// up and» ×3. Отсюда и порог: связку схлопываем с третьего раза, одинокое
// слово — с пятого, за которым человек в эталоне уже не встречается.
//
// Раньше этих правил было два: воркер звал одно (с четвёртого раза, оставить
// два), сборщик реплик — другое (с третьего, оставить одно). Текст проходил
// через оба, и до зрителя доезжало то, что мягче: залипание на тринадцать
// повторов оставляло на экране лишний дубль, потому что после первого прохода
// их становилось два, а два — это уже не повтор для второго.

/** Слово без регистра и знаков: сравниваем звучание, а не пунктуацию. */
const norm = (w) => w.toLowerCase().replace(/[^\p{L}\p{N}']/gu, '');

// Длина повторяющегося куска. Срывается модель обычно на одном слове, но
// бывает и на связке: «and then. and then. and then.». Длиннее шести слов
// зацикливания не бывает: у декодера в петле короткая память.
const MAX_GRAM = 6;

/** Сколько повторов подряд считать сбоем — по длине повторяемого куска. */
const runFor = (gram) => (gram === 1 ? 5 : 3);

const same = (w, i, j, k) => {
  if (j + k > w.length) return false;
  for (let n = 0; n < k; n++) if (w[i + n] !== w[j + n]) return false;
  return true;
};

/**
 * Свернуть зацикленные повторы.
 *
 * @param {string} text распознанное, как его выдала модель
 * @returns {string} тот же текст, но каждый залипший повтор — один раз
 */
export function unloop(text) {
  const raw = (text || '').split(/\s+/).filter(Boolean);
  if (raw.length < 3) return text || '';

  const w = raw.map(norm);
  const out = [];
  for (let i = 0; i < raw.length;) {
    let took = 0;
    // Короткий кусок важнее длинного, и это не мелочь. «big big big big» —
    // это петля из одного слова, но её же видно и как петлю из двух слов
    // «big big», и свернуть по двойке значит оставить вдвое больше, чем
    // нужно. Обратной ошибки тут быть не может: «we gotta win we gotta win»
    // по одному слову и по двум не сходится вовсе — там просто нет повтора
    // такой длины, — и до тройки очередь дойдёт нетронутой.
    for (let k = 1; k <= MAX_GRAM && !took; k++) {
      if (i + k * runFor(k) > raw.length) continue;
      let runs = 1;
      while (same(w, i, i + runs * k, k)) runs++;
      if (runs < runFor(k)) continue;
      // Знаки препинания у повторов разные («big,» и последнее «big.»), и
      // взять надо первые: последний обрывается там, где кончился лимит.
      for (let n = 0; n < k; n++) out.push(raw[i + n]);
      i += runs * k;
      took = 1;
    }
    if (!took) out.push(raw[i++]);
  }
  return out.join(' ');
}
