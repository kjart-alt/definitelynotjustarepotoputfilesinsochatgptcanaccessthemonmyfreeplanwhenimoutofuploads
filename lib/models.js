import { NEMO_LANGS } from './nemo-langs.js';

// Каталог сборок распознавания. offscreen.js и live-worker.js берут отсюда
// адрес весов, длину куска и путь к графу кодировщика.
//
// Роль одна — живая строка, и держит её только потоковая модель. Всё, что
// выдаёт текст позже полутора секунд после сказанного, из расширения убрано:
// оконные модели (whisper, moonshine) и точная дорожка (parakeet, turbo)
// ждали конца фразы или окна и приносили слово через пять, десять, двадцать
// пять секунд. Субтитры, которых надо столько ждать, не читает никто, сколь
// бы точны они ни были.
//
// Поэтому вся работа над качеством — это работа над одной nemotron: какая
// сборка, какой кусок, какой слот языка. Замеры — у карточек ниже.

// Nemotron, cache-aware streaming. Оконным моделям (whisper, moonshine,
// parakeet) дают вырезанный кусок звука, и раньше конца куска им сказать
// нечего: весь счёт задержки у них — ожидание отреза окна, а не проход.
//
// Cache-aware streaming устроен иначе: кодировщик держит контекст в кеш-
// тензорах и считает только новые 560 мс. Ждать нечего, пересчитывать нечего.
// Замер на трёх минутах ролика (e2e/nemo-live.mjs, кодировщик на видеокарте,
// RNN-T на процессоре):
//
//   проход куска (медиана)        313 мс
//   он же, 95-й процентиль        499 мс
//   доля реального времени        0.61
//   слово на экране               0.59 с  (280 мс полкуска + проход)
//
// И тот же ролик по точности, против человеческой дорожки (texts/):
//
//   дорожка                    слово на экране   F1 (en)   смысл en   смысл ru
//   точная, whisper-turbo           ~13 с          97.4      91.9       91.7
//   автодорожка ютуба              офлайн          96.1      88.4       91.6
//   эта                             0.59 с         93.6      88.8       87.5
//   moonshine-base                  2.6 с          74.5      70.4       77.8
//
// Точная whisper-turbo в таблице — для меры: её слово доезжало до экрана
// через секунды, а не через одну, и из расширения она убрана целиком.
//
// Чем платим: весами. Восемьсот мегабайт против ста шестидесяти у moonshine,
// и это int4 — 394 МБ внутри кодировщика так и остались fp32 (72 обычных
// MatMul и 77 свёрток, которые квантовать не стали).
//
// Формат onnxruntime-genai, три отдельных графа, свой препроцессинг. Всё это — lib/nemo.js и live-worker.js, и поэтому у
// карточки нет dtype: точность зашита в сами файлы.
const NEMOTRON = {
  id: 'onnx-community/nemotron-3.5-asr-streaming-0.6b-onnx-int4',
  name: 'потоковая',
  note: 'по умолчанию: слово на экране за секунду, 35 языков',
  mb: 788,
  streaming: true,
  // Языки, на которых модель печатает текст. Номер слота lang_id для каждого
  // взят из её же чекпойнта (prompt_dictionary в model_config.yaml), а не
  // угадан перебором — см. lib/nemo-langs.js.
  langs: NEMO_LANGS,
  dtype: null,
  // Длина куска: 56 мел-кадров по 10 мс. Она не свойство породы, а свойство
  // экспорта — cache-aware модели NVIDIA учат на нескольких задержках сразу, и
  // в чекпойнте лежат все. У сборки onnx-community зашито 560 мс.
  chunkFrames: 56,
  // Кодировщик на видеокарте требует переписанного графа: в исходном есть
  // Concat на 24 входа, а WebGPU даёт шейдеру не больше восьми буферов. У
  // этой сборки такого графа на huggingface нет, и правленый лежит в attic/
  // (стенд достаёт его оттуда). Сама она — лишь основа для своих сборок: у тех
  // граф лежит рядом с весами, и поле пустое (см. NEMO_320).
  graph: 'models/nemo/encoder-split.onnx'
};

/**
 * Та же модель, переэкспортированная из чекпойнта NeMo своими руками.
 *
 * Зачем. У сборки onnx-community 48 матриц кодировщика сращены в com.microsoft
 * FusedMatMul, квантователь их не берёт, и 223 млн весов остались fp32 — отсюда
 * и 690 МБ кодировщика, и лишняя работа видеокарте. Свой экспорт с basic-
 * оптимизацией квантуется целиком: 394 МБ и проход вдвое дешевле. Замер на трёх
 * минутах v9QtM6qnG50 (кодировщик на видеокарте, RNN-T на процессоре, одна
 * модель на машине):
 *
 *   сборка            кусок  проход куска  доля реального времени  F1
 *   onnx-community    560 мс     361 мс            0.64×          92.5%
 *   своя              560 мс     248 мс            0.44×          93.7%
 *   своя              320 мс     180 мс            0.56×          92.4%
 *
 * Полная таблица и перебор длины куска — texts/кусок/ИТОГ.txt. Перебор повторён
 * 1 октября, после того как проход подешевел (кеш предиктора, кеши кодировщика
 * в буферах видеокарты) — выводы те же, но числа другие:
 *
 *   кусок   задержка до закрытия куска   F1      проход   успевает за звуком
 *   320 мс            0.64 с           93.1%    155 мс         0.48×
 *   160 мс            0.60 с           92.1%    123 мс         0.77×
 *    80 мс            0.60 с           91.3%    107 мс         1.34×
 *
 * Короче 320 мс идти нельзя и теперь: 160 покупает 40 мс задержки за целый
 * пункт точности и половину запаса машины, а 80 за звуком уже не успевает.
 *
 * Сам NEMO_320 с 1 октября — DEFAULT_DRAFT: это и есть живая дорожка зрителя,
 * и веса её едут в пакете. Соседнюю 560 можно выбрать лишь ключом стенда
 * (node e2e/subtitles.mjs --draft=local/nemo-560b): она лежит только в его
 * зеркале.
 */
const NEMO_320 = {
  ...NEMOTRON,
  id: 'local/nemo-320b',
  name: 'потоковая',
  // Ноль — веса едут в пакете, качать нечего.
  note: 'по умолчанию: в пакете, слово на экране за секунду',
  mb: 0,
  chunkFrames: 32,
  graph: '',
  // Статизированный граф: длины куска и кеша зашиты внутрь константами, а
  // подсказка языка приходит готовым вектором. Формовой арифметики в нём из-за
  // этого не осталось вовсе — 1763 узла против 3519, и ни один больше не
  // спускается на процессор посреди прохода. Замер на трёх минутах ролика
  // (e2e/nemo-probe.mjs, кодировщик на видеокарте): проход куска 172 мс против
  // 185, доля реального времени 0.54× против 0.58×, текст побитово тот же.
  // Собирается tools/веса-в-пакет.sh.
  encoder: 'encoder-static.onnx',
  // Расширение считает только этим: кодировщик свой, на Rust (lib/nemo-rs.js),
  // те же int4-веса пакета, раскладка по encoder-rs.json, добавка — 25 МБ.
  // Проход 320 мс стоит ~31 мс в четыре потока (i5-13500H, 22.10). encoder и
  // graph выше нужны только стендам с ORT на видеокарте.
  //
  // Прежде здесь был граф ORT на int8 с куском 1120 мс: на 320 и 560 он за
  // звуком не успевал (проход 434 и 575 мс), а на 1120 стоил 775 мс и слово
  // доходило до экрана за 1.34 с (e2e/nemo-live.mjs --device=wasm, 10.10).
  cpu: { layout: 'encoder-rs.json', extra: 'encoder-cpu.extra', chunkFrames: 32 }
};
const NEMO_560 = { ...NEMO_320, id: 'local/nemo-560b', name: 'потоковая 560',
  note: 'своя сборка, кусок 560 мс', mb: 490, chunkFrames: 56,
  // Сборку на 560 мс статизировать незачем: она лежит только в зеркале стенда.
  encoder: 'encoder-split.onnx', cpu: null };

/**
 * Сборка зрителя одна: многоязычная из пакета. Качать ничего не надо, и язык
 * она определяет сама; выбора модели в панели поэтому нет. Сборка
 * onnx-community, с которой всё начиналось, в список не входит: своя точнее её
 * (93.1 против 92.5 F1) и не требует скачивания, — каталогу она нужна как
 * основа, от которой наследуют свои.
 */
export const DRAFTS = [NEMO_320];

/**
 * Сборки, которые есть только у стенда (ключ --draft): у зрителя нет зеркала
 * их весов. Каталог о них знать обязан — иначе воркер не узнает ни длины
 * куска, ни где лежит граф.
 */
export const EXPERIMENTAL = [NEMO_560];

export const DEFAULT_DRAFT = NEMO_320.id;

const ALL = [...DRAFTS, ...EXPERIMENTAL];

/**
 * Какую сборку на самом деле запускать. Из прошлых версий в настройках может
 * остаться id модели, которой больше нет (оконные, английская): такой зритель
 * получает сборку по умолчанию.
 *
 * @param {string} id что выбрано в настройках
 * @returns {string} id модели, которую можно запускать
 */
export function draftFor(id) {
  return ALL.some(d => d.id === id) ? id : DEFAULT_DRAFT;
}

/** Запись каталога по id. Неизвестный id — сборка по умолчанию. */
export const findModel = (id) => ALL.find(m => m.id === id) || NEMO_320;
