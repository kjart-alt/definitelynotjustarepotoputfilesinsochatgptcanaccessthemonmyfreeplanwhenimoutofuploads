// Лента субтитров: что из сказанного показать и в каком порядке.
//
// Чистые функции над списком реплик, без DOM и без chrome.*: их зовёт и панель
// (ext/sidepanel.js), и тест (test/cues.test.mjs) — один и тот же код, а не
// копия в тесте.

import { HARD_END, CLOSERS } from './stitch.js';

// Лента одна, а не две строки.
//
// Расширение слушает двумя моделями сразу. Быстрая отдаёт фразу через 2–3
// секунды после того, как её договорили, точная — через 8–9. Раньше у каждой
// была своя строка: сверху точная, снизу быстрая. На экране от этого стояли
// одновременно два разных места ролика, секунд на одиннадцать врозь, и читать
// это было нельзя — ровно то, что зритель называет «непонятно, что
// переводишь».
//
// Поэтому лента одна и идёт по порядку речи: новая строка встаёт внизу,
// прочитанные уезжают вверх и гаснут. Ведёт её быстрая модель — только она
// поспевает за картинкой. Точная не заводит второй ленты, а переписывает в
// этой же те строки, до которых ещё дотягивается.
//
// Дотягивается она редко, и это замерено, а не предположено: на трёхминутном
// ролике её текст приезжает в среднем через шесть строк после того места, к
// которому относится. Пока лента была субтитром поверх картинки и держала три
// строки, шесть из семи правок опаздывали и уходили только в расшифровку.
// Боковая панель Chrome высотой в окно держит их все — за это она и заведена.

// Сколько строк держим в виде. Панель во всю высоту окна вмещает около
// тридцати; лишние узлы стоят каждый показ, а прочитать их всё равно некому.
export const ROWS = 40;

// Сколько реплик помним. Память должна быть больше страницы, а не меньше: в
// пределе каждая строка страницы — своя реплика, и стоило памяти кончиться
// раньше страницы, как её начало вытеснялось прямо из-под глаз. Панель этого
// не замечала и молча съезжала на освободившееся место — на замере трёх минут
// прочитанное так уезжало трижды, по 75 px за раз, без всякого затухания.
// Отсюда и «текст дёргается»: уезжало не новое, а уже прочитанное.
//
// Сверх страницы помним ещё столько же — на опоздавшую правку точной модели:
// её текст приезжает в среднем через шесть строк после своего места, а в
// пределе отстаёт на всю очередь.
export const KEEP = ROWS + 24;

// Предел строки субтитра. Человек-редактор держится в этих же рамках, и не
// от вкуса: строка длиннее читается дольше, чем висит.
export const MAX_WORDS = 12;

// Письмо без пробелов (японский, китайский, тайский) пробелами слов не
// разделяет: «слово» там выходит длиной во всю реплику, предел строки не
// срабатывает ни разу, и субтитр уезжает на пять визуальных строк. Единица
// счёта там — знак: двенадцать знаков японского как раз и есть нормальная
// длина строки субтитра.
const SOLID = '\\u3040-\\u30ff\\u3400-\\u4dbf\\u4e00-\\u9fff\\uf900-\\ufaff\\u0e00-\\u0e7f';
const HAS_SOLID = new RegExp(`[${SOLID}]`, 'u');

// Единица счёта в слитном письме: один знак письма либо целая связка
// непробельных знаков рядом с ним. Связка нужна, чтобы латинское слово, число
// и знак конца мысли не рассыпались на буквы: «AI」 внутри японской реплики —
// одна единица, а не две, и считать её за две значило бы резать строку чаще,
// чем нужно.
const UNITS = new RegExp(`[${SOLID}]\\p{M}*|[^\\s${SOLID}]+`, 'gu');

// Тайское письмо — слитное, но по знакам его резать нельзя: гласная пишется
// перед своей согласной (เรา) или над ней (วัน), и знак, оторванный от
// согласной, это уже не текст, а опечатка на весь перенос. Границы слов там
// знает Intl.Segmenter со словарём ICU — он есть и в Chrome, и в Node.
const THAI = /[\u0e00-\u0e7f]/u;
const thaiWords = typeof Intl !== 'undefined' && Intl.Segmenter
  ? new Intl.Segmenter('th', { granularity: 'word' })
  : null;

export const words = (t) => {
  const s = (t || '').trim();
  if (!s) return [];
  if (!HAS_SOLID.test(s)) return s.split(/\s+/).filter(Boolean);
  // Смешанный текст встречается постоянно: латинское название внутри японской
  // реплики, цифры, знаки конца мысли. Поэтому письмо выбирается на каждом
  // куске, а не один раз на всю строку.
  return s.split(/\s+/).flatMap((piece) => {
    if (thaiWords && THAI.test(piece)) return [...thaiWords.segment(piece)].map(x => x.segment);
    return piece.match(UNITS) || [];
  }).filter(Boolean);
};

// Знаки, рядом с которыми пробела в письме не бывает: кана, иероглифы, тайский,
// а с ними вся широкая пунктуация (。、！？ и полноширинные скобки). Нужны они
// обратной склейке: единицы счёта в слитном письме — знаки, и склей их через
// пробел, как латинские слова, — вместо «皆さんこんにちは。» на экране встанет
// «皆 さ ん こ ん に ち は 。». Ровно это и вышло с первой правкой words():
// предел строки на японском заработал, а текст стал нечитаемым.
const NOSPACE = new RegExp(
  `[\\u2e80-\\u303f${SOLID}\\ufe30-\\ufe4f\\uff00-\\uff60]`, 'u');

/** Чем склеить две единицы обратно: пробелом или ничем. */
const sep = (a, b) => (NOSPACE.test(a.slice(-1)) || NOSPACE.test(b.slice(0, 1)) ? '' : ' ');

/** Склеить единицы в строку так, как они стояли в тексте. */
const glue = (parts) => parts.reduce((s, p) => (s ? s + sep(s, p) + p : p), '');

/** Границы предложений, запятых и союзов — в порядке убывания качества реза. */
export const SPLITS = [
  /(?<=[.!?…]["'»)\]]*)\s+/,
  // Та же граница в письме без пробелов: за широкой точкой пробела не бывает,
  // и без этого шва японская реплика резалась не по предложениям, а по
  // двенадцать знаков подряд — ровным столбиком, рвущим фразу посередине.
  new RegExp(`(?<=[${HARD_END}]${CLOSERS}*)`, 'u'),
  /(?<=[;:—–])\s+/,
  /(?<=,)\s+/,
  // Запятая слитного письма — последний шов перед резкой по счёту.
  /(?<=[、，；：])/u
];

/** Разрезать кусок, который всё ещё длиннее предела, лучшим доступным швом. */
export function chop(text, live = false) {
  if (words(text).length <= MAX_WORDS) return [text];
  for (const re of SPLITS) {
    const parts = text.split(re).filter(Boolean);
    if (parts.length > 1) return parts.flatMap(p => chop(p, live));
  }
  // Швов нет вовсе — речь без единой паузы. Тогда режем по словам на равные
  // части: ровных частей ровно столько, сколько нужно, чтобы каждая влезла
  // в предел, и ни одна не оказалась заметно длиннее соседней.
  //
  // Кроме живой строки: она прирастает словом за словом, и при делении поровну
  // каждое новое слово сдвигает шов — первая часть то растёт на визуальную
  // строку, то сжимается, и это видно как дрожь (13–21 слово перевода, место
  // стоит, низ первой части скачет на 21 px). У живой первые части полные, по
  // MAX_WORDS, и новые слова ложатся только в последнюю.
  const w = words(text);
  const n = Math.ceil(w.length / MAX_WORDS);
  const size = live ? MAX_WORDS : Math.ceil(w.length / n);
  return Array.from({ length: n }, (_, i) => glue(w.slice(i * size, (i + 1) * size)));
}

/**
 * Реплика → строки субтитров. Точная модель отвечает не фразой, а всем, что
 * успело накопиться у неё в очереди: на замере её реплики выходили по 26 слов
 * в среднем и до 56 в пределе. После реза мелкие куски склеиваются обратно,
 * пока влезают: «Да.» отдельной строкой — это мигание, а не субтитр.
 */
export function lines(text, live = false) {
  const out = [];
  for (const piece of chop((text || '').trim(), live)) {
    const last = out.at(-1);
    if (last && words(last).length + words(piece).length <= MAX_WORDS) out[out.length - 1] = last + sep(last, piece) + piece;
    else out.push(piece);
  }
  return out.filter(Boolean);
}

/**
 * Тот же текст, но на n частей, пропорционально словам. Нужен оригиналу под
 * лентой: у перевода своё число предложений, и совпасть по швам они не
 * обязаны — важно лишь, чтобы серая строка шла примерно о том же.
 */
export function into(text, n) {
  const w = words(text);
  if (n <= 1 || !w.length) return [text || ''];
  const size = w.length / n;
  return Array.from({ length: n }, (_, i) =>
    glue(w.slice(Math.round(i * size), Math.round((i + 1) * size))));
}

/**
 * Быстрая модель сказала своё. Пока фраза не закрылась, она приходит
 * снимками по нескольку раз, и все они — одна и та же строка ленты, которая
 * дописывается на глазах, а не столбик почти одинаковых строк.
 *
 * Так же растёт и строка из закрытых кусков, пока говорящий не договорил
 * предложение: недоговорённое придерживается и приходит снова вместе с
 * продолжением (line в offscreen.js). Номер строки у них общий — по нему
 * и видно, что это одна строка, а не две похожие.
 *
 * @param {Array} cues лента, меняется на месте
 * @param {object} cue реплика: from, to — номера фраз, line, text, orig, open, lag
 * @param {number} keep сколько строк держать; Infinity — расшифровка всего сеанса
 * @returns {boolean} легла ли реплика в ленту; false — это шаг назад
 */
export function feed(cues, cue, keep = KEEP) {
  const top = cues.at(-1);
  // Снимок незакрытой фразы живёт ровно до текста по той же фразе целиком:
  // тот сказан той же моделью, но законченной фразой, и заменяет снимок.
  // Обычно под незакрытой строкой лежит та, которую она дописывает: снимок
  // фразы рисуется поверх растущей строки, и расти должна именно нижняя.
  // У потоковой дорожки снимка нет вовсе — незакрытая строка сама и есть
  // растущая, и заменять её надо на месте, а не класть рядом вторую такую же.
  const under = (top?.open && top.line !== cue.line) ? cues[cues.length - 2] : top;
  const grows = under && cue.line != null && under.line === cue.line;
  // Та же это строка или новая — знает только line. Номера фраз у соседних
  // строк потоковой дорожки заходят друг на друга: пока строка открыта, поток
  // успевает съесть звук следующей фразы и строка объявляет её своим концом
  // (endPhrase в offscreen.js), а закрывается всё равно на предыдущей. По этим
  // номерам лента и рвалась: закрытие своей же строки читалось как шаг назад и
  // отвергалось, строка навсегда оставалась открытой, а следующая признавалась
  // её повтором и выбрасывала — на экране всё время висела ровно одна реплика,
  // и каждые четыре секунды прочитанное исчезало целиком. Отсюда и «слова
  // съедаются, а на новую строку не переходит».
  //
  // Поэтому: есть line у обеих — судим по нему, нет — по номерам фраз, как
  // судили оконные снимки, у которых номера сплошные.
  const numbered = cue.line != null && top?.line != null;
  // Договорённая строка не оживает. Открытый снимок той же строки после её
  // закрытия — это опоздавший перевод: его начали до закрытия, текста в нём
  // меньше, и встань он на место закрытой — снял бы с неё последние слова и
  // снова зажёг курсор. Слова эти при этом уже не вернутся: речь ушла в
  // следующую строку. Номер строки поток только увеличивает, так что «открытое
  // после закрытого» — всегда опоздавшее.
  if (grows && under.open === false && cue.open) return false;
  // Шаг назад: пришло то, что старше показанного. Своей же строке это не
  // касается — её и дописываем.
  if (!grows && top && (numbered ? cue.line < top.line : cue.to < top.to)) return false;
  // Повтор уже договорённой строки. Но только если это та же строка: у разных
  // строк номера фраз совпасть могут, а вот line — нет.
  if (!grows && top && !top.open && cue.to === top.to && !numbered) return false;
  // Незакрытую строку заменяет только та же фраза. Речь ушла дальше — значит
  // эту строку уже не допишут, и она договорена: в ленте она остаётся, а не
  // выбрасывается новой.
  //
  // Это не мелочь, это была вся лента. Пока черновая модель делала по фразе
  // закрытый проход, строку закрывал его текст, и лента росла. Проход убрали
  // (DRAFT_CLOSED в offscreen.js) — закрывать стало нечем, каждая строка
  // осталась открытой навсегда, и следующая её сносила. На записи прогона 38
  // из 553 показов экран держал одну строку 413 раз и три — пятнадцать;
  // зритель читал бегущую строку без начала и конца, а «обрыв на полуслове»
  // в отчёте был не обрывом речи, а исчезнувшим продолжением.
  //
  // И та же строчка вернула на экран точную модель: fix ниже правит только
  // договорённое, а договорённого в ленте не было ни одного — отсюда ноль
  // правок из двадцати одной в двух прогонах подряд. С этой правкой на той
  // же записи в ленту ложатся все двадцать одна.
  //
  // Но только когда строка не растёт. Пока росла — этой же строчкой её и
  // выбрасывало: прибавка потока приходит с тем же номером фразы и тем же
  // line, дальше Object.assign дописывал уже выброшенный объект, и в ленте
  // его не было. На экране живая строка мигала через одну прибавку: «Сначала
  // мы» → пусто → «Сначала мы заливаем бетон» → пусто. Отсюда и «непонятно,
  // какое слово текущее»: зацепиться глазу было не за что, а устойчивый текст
  // появлялся только на закрытии фразы, то есть секунды спустя.
  const same = top?.open && cue.to === top.to && !(numbered && cue.line !== top.line);
  if (grows) {
    // Снимок той же фразы поверх растущей строки устарел: прибавка несёт то
    // же самое и дальше. Саму растущую строку (top === under) не трогаем —
    // её и дописываем.
    if (same && top !== under) cues.pop();
  } else if (same) cues.pop();
  // Пришла другая строка — предыдущая договорена. Снимаем с неё не только
  // «открыта», но и «растёт»: расти ей больше нечем, речь ушла дальше.
  //
  // Флаг этот снимался раньше только приходом новой прибавки к той же
  // строке, а её не бывает: поток начал следующую. Строка так и оставалась
  // растущей навсегда, а fix растущие пропускает — и всякая правка,
  // наткнувшись на такую строку, начинала замену за ней. Строка перед
  // правкой оставалась черновой до конца ролика: в прогоне 30 сентября это
  // девять строк из двадцати семи прочитанных, и они целиком объясняли,
  // почему точная модель переписала восемнадцать реплик из двадцати одной,
  // а на экране осталась почти четверть черновика.
  else if (top && (top.open || top.growing)) { top.open = false; top.growing = false; }
  // from не трогаем: строка начинается с той фразы, с которой начиналась, и
  // по ней точная модель потом найдёт, что именно переписывать.
  // to у строки только растёт: им мерят и «шаг назад», и то, до какого места
  // дотянулась точная модель, а закрытие приходит с фразой, на которой речь
  // кончилась, — она меньше той, до которой строка успела дорасти.
  if (grows) Object.assign(under, cue, { from: under.from, to: Math.max(under.to, cue.to) });
  else cues.push(cue);
  if (cues.length > keep) cues.splice(0, cues.length - keep);
  return true;
}

/**
 * Точная модель догнала часть ленты. Её реплика накрывает всё, что быстрая
 * успела наговорить по тем же фразам, — эти строки и заменяем одной.
 *
 * Незакрытую строку внизу не трогаем никогда: там говорят прямо сейчас,
 * точная модель до туда не дошла, и заменять её нечем. Растущая строка —
 * такая же незакрытая: предложение в ней ещё договаривают.
 *
 * @returns {boolean} нашлось ли что заменить; false — реплика опоздала,
 *   места в ленте ей уже нет, а дописать её в конец нельзя: там чужое время
 */
export function fix(cues, cue) {
  const ready = (c) => !c.exact && !c.open && !c.growing;
  const from = cues.findIndex(ready);
  if (from < 0) return false;
  let to = from;
  while (to < cues.length && ready(cues[to]) && cues[to].to <= cue.to) to++;
  if (to === from) return false;
  // at — когда строку показали впервые: по нему расшифровка ставит время.
  cues.splice(from, to - from, { ...cue, from: cues[from].from, at: cues[from].at, open: false, exact: true });
  return true;
}

/**
 * Что показать: последние rows строк ленты, сверху вниз по времени речи.
 *
 * Строка помнит, из какой реплики она нарезана и какая она там по счёту, —
 * по этому оригинал под лентой берётся ровно от нижней строки, а не от всей
 * реплики целиком.
 */
export function visible(cues, rows = ROWS) {
  const out = [];
  for (let i = cues.length - 1; i >= 0 && out.length < rows; i--) {
    const parts = lines(cues[i].text, !!(cues[i].open || cues[i].growing));
    for (let j = parts.length - 1; j >= 0 && out.length < rows; j--) {
      out.unshift({ text: parts[j], cue: cues[i], part: j, parts: parts.length });
    }
  }
  return out;
}

// Сколько строк, ещё не переписанных точной моделью, переносим на новую
// страницу вместе с живой.
//
// Не «сколько наберётся»: если точной модели нет вовсе — её выключили или она
// не знает языка речи, — черновыми будут все строки подряд, и перенос
// превратил бы переворот в построчную прокрутку, ровно ту дрожь, ради
// избавления от которой страница и заведена.
//
// Пять — по замеру, а не на глаз. e2e/page-replay.mjs гоняет один и тот же
// записанный поток реплик под разными значениями; на пяти записях доля
// черновика в прочитанном падает с 22–23% (без переноса) до 15.1, 15.1, 8.6,
// 7.8 и 10.5% при трёх строках и до 5.0, 5.0, 4.7, 6.9 и 5.0% при пяти.
// Дальше пяти не меняется ничего — столько точная модель и отстаёт. Цена
// нулевая: переворотов во всех случаях поровну.
export const CARRY_ROWS = 5;

/**
 * С какой строки начинать новую страницу, когда место кончилось.
 *
 * Точная модель отстаёт от живой примерно на окно, поэтому нижние строки
 * страницы всегда ждут её правки. Переворот уносил их черновыми, и правка
 * приходила в пустоту: в замере так прочиталось шесть строк из двадцати шести
 * — 13.6% текста, хотя точный вариант приходил через 0.5…7 с после переворота.
 * Значит, нижние черновые строки едут на новую страницу вместе с живой, и там
 * их ещё успевают переписать.
 *
 * Шагаем целыми репликами: начинать страницу с середины реплики незачем.
 *
 * @param {Array} all строки ленты, как их отдал visible
 * @param {number} start начало нынешней страницы
 * @param {number} max сколько строк можно унести с собой
 * @returns {number} начало новой страницы; всегда больше start, иначе место
 *   не освободится и перебор в панели не кончится
 */
export function nextPage(all, start, max = CARRY_ROWS) {
  const head = all.findIndex(r => r.cue === all.at(-1).cue);
  let from = head;
  if (all.some(r => r.cue.exact)) {
    while (from > start && !all[from - 1].cue.exact) {
      const prev = all[from - 1].cue;
      let at = from - 1;
      while (at > start && all[at - 1].cue === prev) at--;
      if (head - at > max) break;
      from = at;
    }
  }
  return from > start ? from : start + 1;
}
