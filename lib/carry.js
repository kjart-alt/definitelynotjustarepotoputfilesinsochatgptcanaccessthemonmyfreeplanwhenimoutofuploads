// Недоговорённый хвост куска: что придержать до следующего раза.
//
// Переводчик получает текст куском и переводит его как самостоятельное
// высказывание. Куску, оборванному по таймеру посреди предложения, это ломает
// грамматику. Слова при этом распознаны верно все до одного, а читать нельзя:
//
//   …The current tunnel to stop │ flooding is three feet wide
//   ⇢ «Текущий туннель, чтобы остановиться» │ «Наводнение имеет ширину три фута»
//
//   …which is why higher │ attendance means less child labor
//   ⇢ «поэтому Более высокая» │ «посещаемость означает меньше детского труда»
//
// Лечится тем, что незаконченное предложение не переводится вовсе, а ждёт
// продолжения в следующем куске. Ждать приходится до конца этого куска, но
// сами слова с экрана не пропадают: черновик незакрытой фразы показывает их
// всё это время, а чистовик приходит уже целой фразой и с целым переводом.
//
// Правило вместе со склейкой перехлёста (lib/stitch.js) собрано в Joiner внизу
// файла. Расширение и стенды зовут именно его: стенд, который повторяет логику
// своими словами, меряет себя, а не расширение.

import { seam, trimOverrun, HARD_END, CLOSERS } from './stitch.js';
import { unloop } from './repeat.js';

/**
 * Конец мысли: знак, за ним, возможно, закрывающая кавычка.
 *
 * Наборов два, и требования у них разные. Латинская точка считается концом
 * только перед пробелом или краем строки — иначе «3.50» и «e.g.» рвали бы
 * предложение посередине. А широкая точка письма без пробелов (。！？ у
 * японского и китайского, । у деванагари, ۔؟ у урду, ። у амхарского, ។ у
 * кхмерского) не требует за собой ничего: пробелов в таком тексте нет вовсе,
 * и ждать их значит не найти конца никогда.
 *
 * Пока ждали, точная дорожка на японском не отдавала на экран ни одной
 * реплики за весь сеанс: каждый её кусок придерживался как недоговорённый и
 * выходил одним куском уже на остановке. Прогон 4jfcE8u9KOM (TEDx, японская
 * речь): 33 закрытых фразы, «готовых реплик 1» — и та с текстом за все три
 * минуты, на экран не попавшая вовсе.
 */
const END = new RegExp(`[.!?…]${CLOSERS}*(?=\\s|$)|[${HARD_END}]${CLOSERS}*`, 'gu');

// Точка не всегда конец: «Mr. Beast», «U.S.», «a.m.», «No. 5». Ходовых
// сокращений с точкой немного, и все они здесь.
const ABBR = /(?:^|\s)(?:mr|mrs|ms|dr|prof|sr|jr|st|vs|etc|inc|ltd|no|approx|fig|e\.g|i\.e|a\.m|p\.m|u\.s)\.$/;

/** Инициал: одна заглавная буква с точкой — «J. Smith», «U.S.A.». */
const INITIAL = /(?:^|\s)\p{Lu}\.$/u;

// Сколько слов можно придержать, прежде чем сдаться. Модель иногда не ставит
// точку целый кусок подряд, и ждать её бесконечно — значит молчать: лучше
// ломаный перевод сейчас, чем безупречный через полминуты.
const MAX_CARRY = 32;

// Больше восьми знаков на «слово» — значит пробелы в этом письме слов не
// разделяют (японский, китайский, тайский), и предел в словах не сработает
// никогда: хвост из одного «слова» короче тридцати двух всегда, какой бы
// длины он ни был. Такой хвост считаем знаками, по два на слово.
const SOLID_WORD = 8;
const SOLID_CHARS = 2;

const ends = (head) => !ABBR.test(head.toLowerCase()) && !INITIAL.test(head);

/**
 * Разделить текст на то, что можно переводить сразу, и недоговорённый хвост.
 *
 * @param {string} text распознанный кусок, уже без перехлёста
 * @param {number=} maxWords сколько слов можно держать в хвосте
 * @returns {{ready: string, tail: string}} ready пуст, если законченного
 *   предложения в тексте нет вовсе и переводить пока нечего.
 */
export function splitTail(text, maxWords = MAX_CARRY) {
  const s = (text || '').trim();
  if (!s) return { ready: '', tail: '' };

  // Нужен последний конец предложения, а не первый: всё до него уже готово.
  let at = -1;
  END.lastIndex = 0;
  for (let m; (m = END.exec(s));) {
    const end = m.index + m[0].length;
    if (ends(s.slice(0, end))) at = end;
    // Шаг на символ, а не за весь знак: «Really?! Yes.» — восклицательный
    // тут стоит вплотную за вопросительным, и пропускать его нельзя.
    END.lastIndex = m.index + 1;
  }

  const ready = at < 0 ? '' : s.slice(0, at).trim();
  const tail = at < 0 ? s : s.slice(at).trim();
  const words = tail.split(/\s+/).filter(Boolean);
  if (words.length > maxWords) return { ready: s, tail: '' };
  // Тот же предел для письма без пробелов. У японской реплики «слово» одно на
  // всю строку, а у тайского знаков конца не бывает вовсе — и там хвост
  // держался бы до самой тишины, то есть до конца ролика.
  if (words.length && tail.length / words.length > SOLID_WORD
      && tail.length > maxWords * SOLID_CHARS) return { ready: s, tail: '' };
  return { ready, tail };
}

/**
 * Сборщик реплик: принимает распознанные куски по одному и отдаёт текст,
 * готовый к переводу. Всё, что мы знаем про стык, живёт здесь — и склейка
 * перехлёста, и придержанный огрызок.
 */
export class Joiner {
  constructor({ maxWords = MAX_CARRY } = {}) {
    /** Прошлый кусок как его выдала модель: по нему ищется перехлёст. */
    this.prev = '';
    /** Недоговорённое предложение, ждущее продолжения. */
    this.carry = '';
    this.max = maxWords;
  }

  /**
   * Закрытый кусок.
   *
   * Оборвана ли фраза — видно по тексту, и только по нему. Раньше придержка
   * включалась от того, как закрылся звук: оборвал ли кусок таймер или тишина.
   * Но тишина между словами бывает и посреди мысли — говорящий взял вдох, —
   * и такой кусок уходил в перевод обрубком:
   *
   *   …the water can't flow through │ it, so it gets backed up…
   *
   * Слова распознаны все до одного, а переводятся как два отдельных
   * высказывания, и оба выходят кривыми. Теперь спрашиваем не звук, а точку в
   * конце: нет её — ждём продолжения, чем бы кусок ни закрылся.
   *
   * @param {string} text распознанное, как есть
   * @param {{overlapped?:boolean, useCarry?:boolean, repeat?:number}} how
   *   overlapped — кусок начинается с хвоста предыдущего;
   *   useCarry — придержанный текст относится именно к нему;
   *   repeat — сколько секунд этого хвоста повторили нарочно, если про это
   *   известно больше, чем знает склейка сама (см. stitch).
   * @returns {string} что можно переводить прямо сейчас; '' — ещё рано
   */
  push(text, how = {}) {
    const whole = this.preview(text, how);
    this.prev = unloop(text);
    const { ready, tail } = splitTail(whole, this.max);
    this.carry = tail;
    return ready;
  }

  /** То же для черновика: показать можно, а состояние трогать нельзя. */
  preview(text, { overlapped = false, useCarry = true, repeat = 0 } = {}) {
    // Срыв генерации снимаем до всего остального: залипший хвост куска — это
    // не речь, и ни склейке, ни придержке он ничего про стык не говорит.
    const said = unloop(text);
    const { text: fresh, slack } = overlapped
      ? seam(this.prev, said, repeat)
      : { text: said, slack: 0 };
    const carry = useCarry ? this.carry : '';
    return `${this.behind(carry, fresh, { overlapped, cut: fresh !== said, slack })} ${fresh}`.trim();
  }

  /**
   * Что осталось от придержанного хвоста, когда пришёл следующий кусок.
   *
   * Хвост держат потому, что предложение не договорено, — и ровно поэтому его
   * конец написан моделью у самого обрыва, где она сочиняет. Пока его не
   * показали, эти слова можно забрать назад, и следующий кусок говорит, сколько:
   *
   *   склейка сработала со сдвигом — списанные ею слова и есть сочинённые:
   *     «…so we're deading» ⇢ «So we're dedicating the next year»
   *     якорь «so we're», «deading» списано — и из хвоста оно уходит тоже,
   *     иначе склеенная строка читается «…so we're deading dedicating…»;
   *
   *   склейка не нашла ничего, а следующий кусок начал пересказывать хвост
   *     заново — это trimOverrun, случай из заголовка lib/stitch.js.
   */
  behind(carry, fresh, { overlapped, cut, slack }) {
    if (!carry || !overlapped) return carry;
    if (!cut) return trimOverrun(carry, fresh);
    if (!slack) return carry;
    const kept = carry.split(/\s+/).filter(Boolean).slice(0, -slack);
    return kept.join(' ');
  }

  /** Огрызок, так и не дождавшийся продолжения: речь кончилась. */
  flush() {
    const tail = this.carry;
    this.carry = '';
    return tail;
  }
}

// Самое длинное слово, которое имеет смысл придержать. Речь без пробелов
// (китайский, японский) иначе уехала бы в хвост целой строкой: там «последнее
// слово» — это вся реплика, и строка не закрылась бы никогда.
const MAX_WORD = 24;

/**
 * Слово договорено, если за ним стоит пробел или знак: оба пишутся после.
 *
 * Знаки тут и широкие тоже (。、！？ и прочие из END): японская строка
 * кончается на 。, и без них она считалась бы оборванной на полуслове.
 */
const WHOLE = new RegExp(`[\\s.,!?…;:)\\]"'»、，；：${HARD_END}]${CLOSERS}?$`, 'u');

/**
 * Отрезать слово, оборванное на полузвуке.
 *
 * Потоковая дорожка закрывает строку там, где сегментатор закрыл кусок, а тот
 * режет речь по часам, когда пауз в ней нет. Разрез приходится посреди слова:
 * модель успела написать «bri», а «dge» досчитается уже после отметки — и
 * уедет в начало следующей строки. На экране это выглядит так:
 *
 *   › …наконец, исправим это, бри
 *   › DGE, а эта деревня больше не затопляет
 *
 * Причём «bri» ещё и переводится отдельным словом, то есть портит не только
 * вид строки, но и её смысл. Поэтому недописанное слово в строку не отдаём:
 * оно ждёт продолжения в следующей, там его допишут целиком.
 *
 * @param {string} text набранное строкой к моменту разреза
 * @returns {{ready: string, tail: string}} ready — что можно показывать,
 *   tail — огрызок слова, с которого начнётся следующая строка. Пустой ready
 *   значит, что показывать пока нечего: строка состоит из одного огрызка.
 */
export function splitWord(text) {
  const s = text || '';
  if (!s || WHOLE.test(s)) return { ready: s, tail: '' };
  const at = s.search(/\S+$/);
  if (s.length - at > MAX_WORD) return { ready: s, tail: '' };
  return { ready: s.slice(0, at), tail: s.slice(at) };
}
