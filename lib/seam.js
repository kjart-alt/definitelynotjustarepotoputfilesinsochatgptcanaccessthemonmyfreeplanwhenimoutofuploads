// Оформление шва между строками ленты — из PR #1 (ветка line-cuts), без его
// нарезки по швам. Замер на нынешних расшифровках (кап 24, точки прибавкой):
// своя нарезка + это оформление — +0.28 COMET [+0.07, +0.50] на семи парах,
// лучше 14 / хуже 8 предложений; нарезка из PR поверх — −0.33, не взята
// (texts/нарезка-PR1-сравнение.2026-10-17.txt).

/** Кончается ли текст концом предложения. */
export const endsSentence = (t) => /[.!?…。！？]["'»”’)\]」』]*\s*$/u.test(t || '');

// Языки перевода, где существительное пишут с заглавной: строчная в начале
// продолжения там испортила бы слово, а не шов.
const NOUN_CAPS = new Set(['de', 'lb']);

/** Есть ли в тексте это слово целиком: имя, пришедшее в перевод как было. */
const hasWord = (t, w) => (t || '').split(/[^\p{L}\p{M}\p{N}'’-]+/u).includes(w);

/** Начинается ли исходник со строчной (английское «I» — тоже середина фразы). */
function startsLower(t) {
  const m = /\p{L}[\p{L}'’]*/u.exec(t || '');
  if (!m) return false;
  const c = m[0][0];
  return c !== c.toUpperCase() || /^I(?:['’](?:m|ve|ll|d))?$/.test(m[0]);
}

/**
 * Перевод строки, которую разрезали посреди предложения, — без следов того,
 * что переводчик принял её за целое.
 *
 * Переводчик Chrome всякий кусок оформляет как предложение: заглавная в
 * начале, точка в конце. У строки, разрезанной посреди фразы, это неправда, и
 * шов видно сразу: «…начиная с нашего первого.» | «Дом в нашем районе.»
 * Точку, которой в исходнике не было, у такой строки (mid) убираем —
 * многоточие, «?» и «!» не трогаем. У строки, которая продолжает фразу
 * предыдущей (cont), первую букву делаем строчной — если исходник и сам
 * начинается со строчной, а первое слово перевода не пришло из исходника как
 * есть («YouTube»).
 *
 * Только посреди фразы: рез по запятой или по слову. Шов перед союзом («…in a
 * screw | if I tried…») — это обычно и есть граница предложения, которую
 * модель не отметила, и там точка с заглавной от переводчика верны: человек в
 * эталоне ставит их там же (замер — e2e/score-mt.py, texts/нарезка/).
 *
 * Слова перевода это не меняет — только оформление шва.
 *
 * @param {string} out перевод
 * @param {string} src что переводили
 * @param {{cont?: boolean, mid?: boolean, target?: string}=} o cont — строка
 *   продолжает фразу предыдущей; mid — сама строка оборвана посреди фразы;
 *   target — язык перевода
 * @returns {string}
 */
export function polish(out, src, { cont = false, mid = false, target = '' } = {}) {
  let s = out || '';
  if (!s || !src) return s;
  if (mid && !endsSentence(src)) s = s.replace(/(?<![.…])[.。](["'»”’)\]」』]*)\s*$/u, '$1');
  if (cont && !NOUN_CAPS.has(target) && startsLower(src)) {
    // Заглавная и дальше строчные или конец слова: «Это», «Я». «США», «YouTube»
    // и «NASA» сюда не попадут — вторая буква у них не строчная.
    const m = /^(["'«„“(\[]*)(\p{Lu})(\p{Ll}[\p{L}\p{M}'’-]*|(?![\p{L}\p{M}]))/u.exec(s);
    const word = m && m[2] + m[3];
    if (m && !hasWord(src, word) && !(target === 'en' && /^I$/.test(word))) {
      let low = m[2];
      try { low = m[2].toLocaleLowerCase(target || undefined); } catch { low = m[2].toLowerCase(); }
      s = m[1] + low + s.slice(m[1].length + 1);
    }
  }
  return s;
}
