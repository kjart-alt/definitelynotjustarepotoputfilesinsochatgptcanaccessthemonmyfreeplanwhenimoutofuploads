// Режет непрерывный поток на куски, которые уйдут в модель.
//
// Три правила, и все три оплачены поломками.
//
// 1. Звук не выбрасывается. Ворота громкости решают только, когда закрыть кусок
//    пораньше, — они не решают, что распознавать. Раньше было наоборот.
//
// 2. Порог речи ограничен сверху долей от самого громкого, что сейчас слышно.
//    Абсолютного потолка тут быть не может: у тихой записи и у громкой он
//    разный. А без потолка порог однажды уходит выше всего, что в звуке вообще
//    бывает, и ворота закрываются навсегда — ровно это и стоило двадцати пяти
//    секунд субтитров подряд. Пол шума тогда задрала защита «это гул, а не
//    речь», и подняться обратно он уже не мог: падает он только ниже сигнала,
//    а его посадили под сигнал. Относительный потолок такое исключает: самая
//    громкая половина звука проходит ворота всегда.
//
// 3. Резать по тишине можно только там, где тишина есть. В ролике с музыкой под
//    каждым словом её нет вовсе — самый тихий процент звука там громче обычной
//    речи. Поэтому кусок в любом случае закрывается по maxMs. Но резать ровно на
//    двенадцатой секунде — значит почти наверняка попасть в середину слова,
//    поэтому рез отступает назад, в самый тихий кадр последних секунд, и уносит
//    остаток в следующий кусок. Тихое место не только спасает слово: перехлёст
//    вокруг него модель слышит как паузу и не выдумывает по нему лишних слов —
//    а по перехлёсту посреди речи выдумывала, и та же мысль приезжала дважды
//    разными словами, которые склейке по словам уже не совпасть.
//
// Гул от речи отличается не громкостью, а тем, что он ровный. Это проверяется
// на готовом куске и решает одно: отдавать его модели или нет. Порога такая
// проверка не касается — именно попытка учить ею ворота и стоила тех
// двадцати пяти секунд.
//
// Чистый класс без обращений к браузеру: он же используется в юнит-тестах
// и в офлайн-прогонах по файлу (e2e/segment-audio.mjs).

export const DEFAULTS = {
  sampleRate: 16000,
  // Столько тишины подряд закрывает набравшуюся фразу — и это прямая плата за
  // задержку. Разбор прогона 22 разложил ожидание слова на две части: 1015 мс
  // оно ждёт, пока сегментатор отрежет окно, и только 780 мс идёт сам проход.
  // Первая часть — вот эта константа плюс половина длины фразы, и семьсот
  // миллисекунд тишины зритель досиживает до конца на каждом слове.
  //
  // Резать раньше выглядит безопасным ровно тем, чем не был безопасен короткий
  // maxMs: рез приходится не в середину слова, а в настоящую паузу. Померили
  // развёрткой (e2e/seams.mjs, moonshine-base, контекст 1 с, тот же ролик):
  //
  //   тишина   кусков   слово в слово   на слух   F1     резов по таймеру
  //   700 мс     47         92.2%        94.3%   92.5%      45 из 47
  //   500 мс     47         91.5%        93.8%   91.8%      43 из 47
  //   300 мс     48         90.7%        92.9%   92.0%      33 из 48
  //
  // Кусков не прибавилось ни одного — и это весь ответ. В речи под музыку пауз
  // длиннее трёхсот миллисекунд почти нет, фразу закрывает не тишина, а maxMs;
  // укорачивая тишину, мы не режем раньше, а только меняем рез по таймеру на
  // рез по паузе в тех же местах. Длина окна та же, ждать зрителю столько же,
  // а полтора пункта слово в слово потеряны.
  silenceMs: 700,
  minPhraseMs: 1500,   // ... а короче этого фраза пережидает паузу и растёт дальше
  longSilenceMs: 2200, // столько тишины закрывает фразу любой длины: человек замолчал
  // Длина окна — это и есть ожидание зрителя: в речи под музыку фразу закрывает
  // таймер, а не тишина (45 резов из 47), и слово ждёт в среднем половину maxMs.
  // Значит укоротить окно — прямой и единственный способ срезать ожидание, не
  // трогая видеокарту. Развёртка (e2e/seams.mjs, черновая moonshine-base, тот же
  // ролик) говорит, чем за это платят:
  //
  //   окно     кусков   слово в слово   лишних   F1
  //   5000 мс    47         92.2%       90.9%   92.5%
  //   4000 мс    63         91.8%       85.8%   89.8%
  //   3000 мс    88         92.2%       74.5%   83.2%
  //   2500 мс   107         92.2%       70.6%   80.8%
  //
  // Полнота не падает вовсе: всё сказанное доходит при любом окне. Рушится
  // точность — модель выдумывает на границе, а границ становится вдвое и втрое
  // больше. Секунда ожидания стоит 2.7 пункта F1, дальше обвал. У точной модели
  // тот же уклон втрое положе (96.8 → 95.2 → 93.8): выдумывает именно черновая.
  //
  // Поэтому окно не трогаем. Ожидание надо брать не укорачивая его, а показывая
  // слово до того, как окно закроется, — это снимок незакрытой фразы, и живёт он
  // в offscreen.js, а не здесь.
  maxMs: 5000,         // предохранитель против речи без единой паузы
  // Двенадцать секунд тут стояли зря. Замер на трёхминутном ролике
  // (e2e/seams.mjs, одна и та же дорожка, turbo): при 12 с — 19 кусков, 649
  // слов человека из 655 и 94.6% слово в слово; при 5 с — 47 кусков, 656 слов
  // и 95.0%. Короткий кусок не хуже, а лучше: модель меньше додумывает.
  //
  // Зато он втрое ближе к речи. Ждать приходится всю фразу плюс счёт, и на
  // двенадцати секундах слово появлялось на экране через 16 с после того, как
  // его сказали. На пяти — вдвое быстрее.
  //
  // Ниже пяти нельзя, и причин теперь две. Первая известна давно: turbo
  // считает пятисекундный кусок 4.8 с, потому что добивает любой вход до
  // тридцати секунд, — при кусках каждые 2.5 с очередь растёт быстрее, чем
  // разбирается. Она про Whisper, и у моделей со счётом по фактической длине
  // звука её нет.
  //
  // Вторая — про саму речь, и она общая. Кусок по 2.5 с был измерен целиком
  // (три минуты ролика, одна черновая moonshine-base, без точной модели):
  //
  //   кусок   слово на экране   слов у нас   слово в слово   лишних   F1
  //   5.0 с        6.1 с           640           90.6%       90.2%   91.3%
  //   2.5 с        4.1 с           791           90.5%       73.1%   81.8%
  //
  // Две секунды задержки куплены за семнадцать пунктов точности, и покупка
  // эта пустая: расслышали мы ровно столько же (90.5% против 90.6%), а вот
  // наговорили на четверть больше. Швы тут ни при чём — из девяноста девяти
  // дословный повтор нашёлся на одном. Врёт модель на самих краях: у неё
  // вдвое больше обрывов, и на каждом она половину слова дослушивает сама.
  // «sweltering heat» стало «12th Street Heat», «means less child labor» —
  // «less shallow. Pretend it's means less». Это не склеивается ничем: обе
  // половины неверны по-разному.
  //
  // Значит, задержку надо отыгрывать не длиной куска, а снимками незакрытой
  // фразы: у них краёв нет вовсе, они показывают речь с её начала.
  seekMs: 2000,        // в каком хвосте искать тихое место, чтобы резать не по слову
  overlapMs: 400,      // сколько звука перед таким резом повторить в следующем куске

  // Подгляд за рез — дослушать куску звук, который и так уедет в следующий, —
  // написан и отменён замером (e2e/seams.mjs, moonshine-base, 47 кусков):
  //
  //   подгляд   слово в слово   точность   F1     не расслышали
  //   нет           94.6%         90.0%   92.2%      36 слов
  //   600 мс        92.5%         88.3%   90.4%      50 слов
  //
  // Задумка была лечить правый край: рез приходится посреди слова, модель не
  // слышит его конца и пишет «waltz» вместо «walls». Но рез и так делается в
  // самом тихом кадре хвоста (seekMs выше), а подгляд кончается где придётся —
  // ровно посреди слова, на 600 мс дальше. Обрыв не убран, а передвинут, и
  // вдобавок повтор в начале следующего куска стал длиннее того, что склейка
  // ищет уверенно: срезано на 40 стыках из 45 вместо 41, и потерянных слов
  // стало в полтора раза больше.
  minMs: 400,          // меньше этого речи внутри куска — значит это был шум
  padMs: 300,          // сколько звука до начала речи приклеить в начало
  floorRms: 0.004,     // тише этого не бывает речи: пустая вкладка, а не тихий голос
  mult: 4,             // во сколько раз речь должна превышать пол шума
  ceilRatio: 0.5,      // выше этой доли от громкого уровня порог не поднимается
  fallFast: 0.3,       // как быстро пол шума проседает вслед за тишиной
  riseSlow: 0.01,      // как медленно он подтягивается вверх
  peakFall: 0.002,     // как медленно оседает оценка громкого уровня
  flatRatio: 1.2       // во сколько раз громкое в куске должно превышать тихое
};

const rmsOf = (frame) => {
  let sum = 0;
  for (let i = 0; i < frame.length; i++) sum += frame[i] * frame[i];
  return Math.sqrt(sum / frame.length);
};

const pct = (sorted, p) => sorted[Math.min(sorted.length - 1, Math.floor(sorted.length * p))];

/**
 * @typedef {{audio: Float32Array, cut: boolean, seconds: number, lead: number}} Chunk
 *   cut — кусок оборвали посреди речи, и следующий начнётся с перехлёста.
 *   Тот, кто читает текст, обязан склеить его с предыдущим (lib/stitch.js).
 *   lead — сколько отсчётов в начале куска повторяют хвост предыдущего. Склейке
 *   по тексту это не нужно, а вот склейке по звуку нужно: тот, кто сливает два
 *   куска в один, обязан выбросить этот повтор, иначе модель услышит слово
 *   дважды и дважды его напишет.
 */

export class Segmenter {
  constructor(opts = {}) {
    this.o = { ...DEFAULTS, ...opts };
    this.noiseFloor = this.o.floorRms;
    this.peak = this.o.floorRms;
    this.reset();
  }

  reset(carry = { frames: [], rms: [] }) {
    this.acc = [...carry.frames];
    this.rms = [...carry.rms];
    this.accLen = this.acc.reduce((n, f) => n + f.length, 0);
    // Повтор — не весь перенос. В следующий кусок уходит и остаток после реза,
    // а он звучит впервые; копией остаётся только перехлёст вокруг самого реза.
    this.lead = carry.lead || 0;
    // Перехлёст — это уже речь: она началась в предыдущем куске.
    this.speech = this.accLen > 0;
    this.loud = false;
    this.speechLen = 0;
    this.silentRun = 0;
  }

  /**
   * Граница между «говорят» и «пауза». Снизу — абсолютный ноль, ниже которого
   * речи не бывает вообще. Сверху — доля от текущего громкого уровня, и это
   * единственное, что не даёт воротам заклинить закрытыми.
   */
  get threshold() {
    return Math.max(this.o.floorRms, Math.min(this.noiseFloor * this.o.mult, this.peak * this.o.ceilRatio));
  }

  ms(samples) { return samples / this.o.sampleRate * 1000; }
  samples(ms) { return ms / 1000 * this.o.sampleRate; }

  /**
   * @param {Float32Array} frame очередной кусок звука
   * @returns {Chunk|null} кусок, если он только что закрылся
   */
  push(frame) {
    const rms = rmsOf(frame);

    // Пол шума проседает быстро и подтягивается медленно: короткая пауза должна
    // опускать порог сразу, а редкий громкий кадр не должен его задирать.
    const k = rms < this.noiseFloor ? this.o.fallFast : this.o.riseSlow;
    this.noiseFloor += (rms - this.noiseFloor) * k;

    // Громкий уровень, наоборот, схватывается мгновенно и оседает неспешно:
    // потолок порога должен знать, насколько громким этот звук вообще бывает.
    this.peak = rms > this.peak ? rms : this.peak + (rms - this.peak) * this.o.peakFall;

    this.acc.push(frame);
    this.rms.push(rms);
    this.accLen += frame.length;

    // Звучит ли речь прямо в этом кадре. speech ниже — про весь кусок («речь
    // в нём уже была»), а панели нужно именно «сейчас»: по этому признаку она
    // показывает, что слова считаются, не дожидаясь самих слов.
    this.loud = rms > this.threshold;
    if (rms > this.threshold) {
      this.speech = true;
      this.speechLen += frame.length;
      this.silentRun = 0;
    } else if (this.speech) {
      this.silentRun += frame.length;
    }

    // Речи ещё не было — держим только короткий разгон, чтобы не срезать первый
    // слог. Всё, что старше, обрезаем: распознавать тишину незачем, и кусок
    // не должен раздуться до maxMs, так и не дождавшись речи.
    if (!this.speech) {
      this.trimHead(this.o.padMs);
      return null;
    }

    // Короткая пауза закрывает фразу только тогда, когда во фразе уже есть что
    // распознавать. Иначе «And…» уезжает в модель отдельным куском: смысла в нём
    // нет, а стоит он ровно столько же, сколько целая реплика — Whisper всё равно
    // добивает любой вход до тридцати секунд.
    const grown = this.ms(this.speechLen) >= this.o.minPhraseMs;
    if (this.ms(this.silentRun) >= (grown ? this.o.silenceMs : this.o.longSilenceMs)) return this.flush();
    if (this.ms(this.accLen) >= this.o.maxMs) return this.flush({ cut: true });
    return null;
  }

  /**
   * Тишина прямо сейчас: сколько её длится подряд и набралось ли во фразе речи
   * на полноценный кусок. Ровно те два числа, по которым push() решает закрыть
   * фразу, — но отданные наружу до того, как решение принято.
   *
   * Нужны они снимку. Пауза в речи — единственный момент, когда фразу видно
   * целиком, и правый край у неё чистый: модель не дослушивает оборванное
   * слово и не выдумывает его конец. Ждать, пока пауза дорастёт до silenceMs
   * и фраза закроется по-настоящему, снимку незачем — он за это время успеет
   * показать всё, что сказано.
   */
  hush() {
    return {
      ms: this.speech ? this.ms(this.silentRun) : 0,
      grown: this.ms(this.speechLen) >= this.o.minPhraseMs
    };
  }

  /** Выбросить из начала всё, кроме последних ms миллисекунд. */
  trimHead(ms) {
    const keep = this.samples(ms);
    while (this.acc.length > 1 && this.accLen - this.acc[0].length >= keep) {
      this.accLen -= this.acc.shift().length;
      this.rms.shift();
    }
  }

  /**
   * Ровный ли кусок. У речи громкость всё время проваливается между словами,
   * у гула или ровного тона — нет. Это единственная проверка «а речь ли это
   * вообще»: она решает судьбу одного куска и ничего не меняет в воротах.
   *
   * Улики нужны весомые, и требования тут нарочно перекошены. Пропустить гул —
   * это один мусорный субтитр раз в maxMs. Забраковать речь — это потерянные
   * слова, которых уже ничем не вернуть. Поэтому короткий кусок не судится
   * вовсе, а ровным считается только то, что ровное почти идеально.
   */
  flat(rms, lenSamples) {
    if (this.ms(lenSamples) < this.o.minPhraseMs) return false;
    const sorted = [...rms].sort((a, b) => a - b);
    return pct(sorted, 0.9) < pct(sorted, 0.1) * this.o.flatRatio;
  }

  /**
   * Индекс кадра, на котором лучше всего оборвать переросший кусок: самый тихий
   * кадр последних seekMs. У речи это промежуток между словами, у речи под
   * музыку — хотя бы смычка между ними.
   *
   * Четверть куска — предел отступа, и это не вкусовщина: всё, что после реза,
   * уезжает в следующий кусок, а тот снова закрывается по maxMs. Отступая на
   * половину, поток продвигается только на половину maxMs за кусок — и мелет
   * одно и то же вдвое чаще, чем нужно.
   */
  quietest() {
    const want = Math.min(this.samples(this.o.seekMs), this.accLen / 4);
    let from = this.acc.length, n = 0;
    while (from > 1 && n < want) n += this.acc[--from].length;
    let best = from;
    for (let i = from; i < this.acc.length; i++) if (this.rms[i] < this.rms[best]) best = i;
    return best;
  }

  /**
   * Звук незакрытого куска, каким он накоплен прямо сейчас. Состояние не трогает:
   * кусок продолжает набираться дальше. Это вход для черновых субтитров —
   * тех, что показываются, пока человек ещё говорит.
   *
   * По умолчанию отдаётся кусок целиком, с самого начала фразы. С since
   * отдаётся только прибавка после прошлого снимка — и тогда строку надо
   * собирать самому (lib/live.js): решает это тот, кто её показывает, потому
   * что цена и выгода тут не в звуке, а в том, когда слово выходит из
   * декодера. Замер и тот и другой — в offscreen.js, у объявления снимка.
   *
   * @param {{since?:number, contextMs?:number}} opts since — сколько отсчётов
   *   фразы уже отдавали; contextMs — сколько звука перед этим местом
   *   повторить, чтобы модель не начинала с обрыва.
   * @returns {{audio:Float32Array, from:number, to:number, repeatSec:number}|null}
   *   null, пока речи набралось меньше minMs — а с since ещё и пока меньше
   *   minMs речи набралось в самой прибавке.
   */
  snapshot({ since = 0, contextMs = 0 } = {}) {
    if (!this.speech || this.ms(this.speechLen) < this.o.minMs) return null;
    const all = join(this.acc, this.accLen);
    const from = Math.min(Math.max(0, Math.round(since)), all.length);
    if (!from) return { audio: all, from: 0, to: all.length, repeatSec: 0 };

    // Речь в прибавке, а не звук: пауза длиной в minMs — это не повод будить
    // модель, она по ней ничего нового не скажет.
    let at = 0, spoke = 0;
    for (let i = 0; i < this.acc.length; i++) {
      const len = this.acc[i].length;
      if (at >= from && this.rms[i] > this.threshold) spoke += len;
      at += len;
    }
    if (this.ms(spoke) < this.o.minMs) return null;

    const ctx = Math.min(from, this.samples(contextMs));
    return {
      audio: all.slice(from - ctx),
      from,
      to: all.length,
      repeatSec: ctx / this.o.sampleRate
    };
  }

  /**
   * Закрыть кусок принудительно — например, при остановке захвата.
   * @param {{cut?: boolean}} opts cut — режем посреди речи, нужен перехлёст.
   */
  flush({ cut = false } = {}) {
    const at = cut ? this.quietest() : this.acc.length;
    const frames = this.acc.slice(0, at);
    const rms = this.rms.slice(0, at);
    const len = frames.reduce((n, f) => n + f.length, 0);
    // Судим по всему окну, а не по огрызку до реза: вопрос в характере звука,
    // и короткая отдаваемая часть — не повод отказываться от суждения.
    const flat = this.flat(this.rms, this.accLen);
    // Речь меряем двумя способами и берём больший. Пересчёт по отдаваемой части
    // честнее — рез мог унести половину куска дальше, — но он судит задним
    // числом по нынешнему порогу, а тот к концу куска мог подрасти. Ошибиться
    // в меньшую сторону нельзя: это выброшенный кусок с речью, то есть слова,
    // которых уже ничем не вернуть. Лишний кусок — всего лишь лишний проход.
    const spoke = rms.reduce((n, v, i) => v > this.threshold ? n + frames[i].length : n, 0);
    const speechLen = Math.max(spoke, Math.min(this.speechLen, len));

    // Всё, что после реза, переносится в следующий кусок — переносится, а не
    // копируется. Копией остаётся только короткий перехлёст вокруг самого реза:
    // на случай, если тихое место оказалось не паузой, а смычкой внутри слова.
    // Четверть куска — предел: перехлёст размером с сам кусок означает, что
    // каждый следующий кусок почти целиком состоит из уже сказанного.
    let from = at, back = 0;
    const want = Math.min(this.samples(this.o.overlapMs), this.samples(this.o.maxMs / 4));
    while (from > 0 && back < want) back += this.acc[--from].length;
    // Про этот кусок «повтор в начале» знает не он сам, а предыдущий рез:
    // это его перехлёст. Запоминаем до reset — тот перезапишет поле уже
    // размером нового перехлёста, для следующего куска.
    const lead = Math.min(this.lead, len);
    this.reset(cut ? { frames: this.acc.slice(from), rms: this.rms.slice(from), lead: back } : undefined);

    if (flat) return null;
    if (this.ms(speechLen) < this.o.minMs) return null;
    return { audio: join(frames, len), cut, seconds: len / this.o.sampleRate, lead };
  }
}

function join(frames, len) {
  const out = new Float32Array(len);
  let at = 0;
  for (const f of frames) { out.set(f, at); at += f.length; }
  return out;
}
