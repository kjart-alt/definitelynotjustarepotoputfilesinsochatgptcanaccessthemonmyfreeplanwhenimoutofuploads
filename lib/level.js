// Выравнивание громкости перед моделью.
//
// Признаки nemotron — лог-мел без нормировки (см. nemo-mel.js), так что
// уровень звука модель видит как есть, и он ей не безразличен. Один и тот же
// ролик стенда на разной громкости (e2e/nemo-node.mjs --gain, 03.10.2026):
//
//   уровень речи, дБ    −7    −13   −19   −25   −31   −37   −43
//   en v9QtM6qnG50     92.6  92.8  93.0  93.2  93.6  92.5  90.9   F1
//
// Громкий MrBeast (3.8% отсчётов в потолке) и тихий звук одинаково роняют
// точность, а между −16 и −31 дБ она почти не меняется и на de, fr, ja.
// Живой захват громкость не держит вовсе: её задают ползунок плеера и
// выравнивание громкости самого ютуба. Поэтому уровень речи держим сами —
// медленно, по блокам 100 мс, без пауз: тишину до цели не дотягиваем.

const BLOCK = 1600;                 // 100 мс при 16 кГц
const GATE = 1e-5;                  // −50 дБ по мощности: ниже — пауза
const TAU = 50;                     // блоков: оценка уровня живёт ~5 с
const MIN_GAIN = 10 ** (-30 / 20);
const MAX_GAIN = 10 ** (20 / 20);

/** Уровень речи, к которому тянем вход, дБ относительно полной шкалы. */
export const TARGET_DB = -28;

export class Level {
  constructor(targetDb = TARGET_DB) {
    this.target = 10 ** (targetDb / 10);
    this.reset();
  }

  reset() {
    this.power = 0;   // оценка мощности речи
    this.n = 0;       // сколько блоков речи учтено
    this.gain = 1;    // до первой речи звук идёт как есть
    this.acc = 0;
    this.fill = 0;
  }

  /**
   * Новый буфер с выровненным уровнем. Множитель меняется только на границе
   * блока, поэтому результат не зависит от того, какими порциями идёт звук.
   */
  apply(pcm) {
    const out = new Float32Array(pcm.length);
    for (let i = 0; i < pcm.length; i++) {
      const x = pcm[i];
      out[i] = x * this.gain;
      this.acc += x * x;
      if (++this.fill === BLOCK) {
        this.block(this.acc / BLOCK);
        this.acc = 0;
        this.fill = 0;
      }
    }
    return out;
  }

  block(p) {
    if (p < GATE) return;
    // Первые блоки берём средним, дальше — скользящим: с первой же фразы
    // уровень верный, а музыкальная заставка не держит его полминуты.
    this.n++;
    this.power += Math.max(1 / this.n, 1 / TAU) * (p - this.power);
    this.gain = Math.min(MAX_GAIN, Math.max(MIN_GAIN, Math.sqrt(this.target / this.power)));
  }
}
