// Склейка текста кусков, которые сегментатор разрезал по живому.
//
// Кусок, закрытый по таймеру, обрывается посреди фразы, и на обоих концах реза
// модель ведёт себя плохо, но по-разному. В конце предыдущего куска ей нечего
// слушать дальше, и она договаривает фразу за человека. В начале следующего у
// неё нет того, что было до, и первые слова выходят комом. Одно и то же место
// речи поэтому приезжает дважды и в разном окружении:
//
//   …the current tunnel to stop │ So the stop flooding is three feet wide
//   …the flooding would prevent │ to prevent kids from even getting
//   …which is why higher        │ Higher attendance means less child labor
//
// Общее у них — якорь: слово, на котором оба куска сошлись. До якоря верен
// предыдущий кусок, он слышал, что было раньше; после якоря верен следующий,
// он слышал, что будет дальше. Значит, из следующего надо срезать всё по якорь
// включительно — и сам повтор, и то, что модель насочиняла перед ним.
//
// Что здесь НЕ лечится: если модель насочиняла в конце предыдущего куска
// («…and now that the village is going to be» вместо «…and now that»), якоря
// нет вовсе и текст остаётся как есть. Срезать в такой ситуации начало
// следующего куска — значит выбросить единственную верную версию этих слов.

/** Слово без регистра и знаков: сравниваем звучание, а не пунктуацию. */
const norm = (w) => w.toLowerCase().replace(/[^\p{L}\p{N}']/gu, '');

const words = (s) => s.split(/\s+/).filter(Boolean);

// Короче этого слово совпадает с чужим началом или концом просто так:
// «ever» внутри «every», «read» внутри «ready» — совпадение, а не то же слово.
const AKIN_MIN = 5;

/**
 * Одно и то же слово, разорванное резом.
 *
 * Рез попадает в середину слова, и обе половины модель дослушивает сама, в
 * разные стороны. Из прогона: «…send in the reinforcement.» ⇢ «Enforcement now
 * we just…», «…you have an entire neighbor.» ⇢ «Neighborhood but what's a
 * city…». Слово одно, написано по-разному, и по равенству такой якорь не
 * находится — на экране остаётся лишнее «Enforcement», которого никто не
 * говорил.
 *
 * Признак берём самый узкий, какой работает: одно слово целиком лежит в
 * начале или в конце другого. «Дописала половину» выглядит именно так.
 * Похожести вообще («classrooms» и «lashrooms») тут мало: под неё подходят и
 * два разных слова, а лишний рез стоит дороже лишнего слова.
 */
const akin = (x, y) => {
  if (x === y) return true;
  const [short, long] = x.length < y.length ? [x, y] : [y, x];
  if (short.length >= AKIN_MIN && (long.startsWith(short) || long.endsWith(short))) return true;
  // Вторая половина того же: слово целиком, но с парой перевранных букв.
  // «reinforcement» ⇢ «Enforcement» — ни началом, ни концом одно в другое не
  // ложится, а слово всё равно одно. Длину берём с запасом: на восьми буквах
  // две ошибки — это опечатка, на четырёх — другое слово.
  return short.length >= AKIN_FUZZY && distance(long, short) <= AKIN_SLIP;
};

// На сколько букв позволено разойтись длинному слову и с какой длины.
const AKIN_FUZZY = 8;
const AKIN_SLIP = 2;

/**
 * Расстояние Левенштейна, но дальше AKIN_SLIP считать незачем: как только
 * видно, что разошлись сильнее, ответ уже не нужен.
 */
function distance(a, b) {
  if (a.length - b.length > AKIN_SLIP) return AKIN_SLIP + 1;
  let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    const row = [i];
    let best = i;
    for (let j = 1; j <= b.length; j++) {
      row[j] = Math.min(prev[j] + 1, row[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
      if (row[j] < best) best = row[j];
    }
    if (best > AKIN_SLIP) return AKIN_SLIP + 1;
    prev = row;
  }
  return prev[b.length];
}

// Насколько длинным бывает повтор. Самого звука в перехлёсте доли секунды
// (overlapMs в lib/segmenter.js) — это слово, ну два. Но модель на обрыве не
// умолкает, а предсказывает продолжение, и повтор выходит длиннее звука: в
// настоящем прогоне встретилось «we now have a» — четыре слова на семи
// десятых секунды. Восемь — запас вдвое; всё, что длиннее, это уже не стык,
// а человек, который правда повторился.
const MAX_WORDS = 8;

// Сколько слов модель успевает наговорить в начале следующего куска до якоря:
// «So the stop…» вместо «stop…», «to prevent…» вместо «prevent…». Потолок тут
// не для красоты: якорное слово может случайно встретиться и дальше по тексту,
// и без ограничения склейка срежет вместе с ним половину новой речи.
const MAX_LEAD = 3;

// А после точки — ни одного. См. stitch: там объяснено, почему.
const STRICT_LEAD = 0;

// Сколько слов умещается в секунду речи, с запасом вверх. Нужно одно: перевести
// известную длину перехлёста из секунд звука в слова, которых ещё не видели.
const WORDS_PER_SEC = 5;

/**
 * Потолок для stitch, когда длина перехлёста известна по звуку.
 *
 * Знает её только тот, кто этот перехлёст сделал: в тексте про него никаких
 * следов нет. Так работает быстрая модель в расширении — ей в начало куска
 * доклеивают секунду прошлого звука (DRAFT_CONTEXT_MS в offscreen.js), и
 * повтор выходит длиннее восьми слов, которых склейке хватает на своём.
 *
 * Ниже MAX_WORDS не опускаемся: короткий перехлёст модель всё равно растягивает
 * тем, что успевает досочинить перед якорем.
 *
 * @param {number} seconds сколько секунд в начале куска звучат второй раз
 */
export const overlapCap = (seconds) =>
  Math.max(MAX_WORDS, Math.ceil((seconds || 0) * WORDS_PER_SEC));

// С какого перехлёста считаем, что про повтор известно точно. Свои доли секунды
// сегментатор повторяет всегда (overlapMs в lib/segmenter.js); всё, что заметно
// длиннее, доклеено нарочно, и тогда повтор в начале куска не предположение, а
// факт: этот звук уже звучал, и модель его уже расшифровывала.
const KNOWN_SEC = 0.6;

// Сколько слов в конце предыдущего куска можно списать на досочинённое.
//
// Модель у обрыва не умолкает, а договаривает фразу за человека, и якорь
// оказывается не в самом конце куска, а на пару слов раньше. Из прогона, все
// стыки одной породы: «…until you have it in» ⇢ «times until you have an entire
// neighborhood», «…getting to the school where we're» ⇢ «getting to the school
// were building», «…floods the surrounding areas come come» ⇢ «surrounding areas
// completely separating». Повтор виден глазом, а суффиксом предыдущего куска он
// не является — мешают эти самые «it in», «where we're», «come come».
const MAX_SLACK = 3;

// Но списывать конец куска задаром нельзя: чем короче якорь, тем дешевле найти
// его случайно, а тут окно поиска и так вдвое шире. Со сдвигом требуем якорь
// подлиннее — на трёх словах подряд совпадение перестаёт быть совпадением.
const SLACK_ANCHOR = 3;

// Что считать не служебным словом. «so we» — пара, которая встречается сама
// собой; «so we're» — уже нет.
const SHORT_WORD = 4;

// Чего стоят эти два правила, на одном и том же звуке (e2e/seams.mjs --from=):
//
//   правило                                    быстрая F1   точная F1
//   без списывания вовсе                          92.2        95.6
//   списывать по слабому якорю (hit ≥ ⅔ n)        92.5        95.4
//   короткий якорь только безупречный             92.7        95.5
//   и списанное убрать из придержанного хвоста    92.7        95.7
//
// Третья строка склеивает лишний стык, но оставляет списанное слово висеть
// перед склейкой («…so we're deading dedicating the next year…») — у точной
// модели это съедало больше, чем давал сам стык. Четвёртая — то же правило,
// доведённое до конца: см. Joiner.behind в lib/carry.js.

// Модель слышит перехлёст в двух разных контекстах, так что пара слов из
// десяти почти всегда расходится. Требовать точного совпадения — значит
// не склеить ничего.
const AGREE = 0.7;

/**
 * Широкие знаки конца мысли: те, что пишут в письме без пробелов. 。！？ у
 * японского и китайского, । у деванагари, ۔؟ у урду, ። у амхарского, ។ у
 * кхмерского. Пробела за ними не бывает, и требовать его — значит не найти
 * конца предложения на этих языках никогда (см. END в lib/carry.js).
 */
export const HARD_END = '。．｡！？⁇⁈⁉।॥۔؟։።፧។៕᠃';

/** Закрывающие кавычки и скобки, в том числе широкие. */
export const CLOSERS = '["\'»)\\]」』”’）〉》]';

// Конец мысли: точка, вопрос, восклицание — возможно, под закрывающей кавычкой.
const ENDED = new RegExp(`[.!?…${HARD_END}]${CLOSERS}*$`, 'u');

/**
 * Сколько слов в начале b — это повтор конца a вместе с тем, что модель
 * дописала перед ним.
 *
 * @param {string[]} a слова предыдущего куска, уже приведённые norm
 * @param {string[]} b слова следующего куска, уже приведённые norm
 * @param {number=} max самый длинный якорь, который ещё считается стыком
 * @param {number=} maxLead сколько слов модель могла наговорить до якоря
 * @param {number=} maxSlack сколько слов в конце a могла досочинить модель
 * @returns {{n:number, slack:number}} n — сколько слов срезать с начала b (0,
 *   если якоря нет); slack — сколько слов при этом списано с конца a.
 */
export function overlapWords(a, b, max = MAX_WORDS, maxLead = MAX_LEAD, maxSlack = 0) {
  let best = { n: 0, lead: 0, slack: 0 };
  // Сдвиг с конца a перебираем от нуля вверх: якорь у самого обрыва вернее
  // того, до которого пришлось списать чужие слова.
  for (let slack = 0; slack <= Math.min(maxSlack, a.length - 1); slack++) {
    const tail = a.length - slack;
    // Смещение перебираем от нуля вверх, длину якоря — сверху вниз: из двух
    // одинаково длинных якорей берём тот, что ближе к началу b, а из двух
    // якорей на одном месте — тот, что длиннее.
    for (let lead = 0; lead <= Math.min(maxLead, b.length - 1); lead++) {
      const limit = Math.min(max, tail, b.length - lead);
      for (let n = limit; n >= 1; n--) {
        if (n <= best.n) break;
        let hit = 0, exact = 0, long = 0;
        for (let i = 0; i < n; i++) {
          const x = a[tail - n + i], y = b[lead + i];
          if (akin(x, y)) hit++;
          if (x === y) { exact++; if (x.length >= SHORT_WORD) long++; }
        }
        // Списали конец куска — якорь должен быть длиннее: окно поиска шире, и
        // случайное совпадение дешевле. Короткий якорь тут проходит только
        // безупречный: каждое слово слово в слово, и хоть одно из них не
        // служебное. Так стык «…so we're deading» ⇢ «So we're dedicating»
        // склеивается по «so we're», хотя списанное слово не похоже ни на что.
        if (slack && n < SLACK_ANCHOR && !(exact === n && long)) break;
        if (hit / n < AGREE) continue;
        if (n === 1 && !anchored(a, b, max)) continue;
        best = { n, lead, slack };
        break;
      }
    }
    if (best.n) break;
  }
  return { n: best.n ? best.n + best.lead : 0, slack: best.n ? best.slack : 0 };
}

/**
 * Можно ли верить якорю из одного слова. При перехлёсте в доли секунды повтор
 * из одного слова — обычное дело, так что отказываться от таких якорей нельзя.
 * Но «the» в конце одного куска и «the» в начале другого — совпадение, и
 * отличить одно от другого можно так: настоящему якорю деваться некуда, он
 * встречается в окне поиска ровно один раз с каждой стороны.
 */
function anchored(a, b, max) {
  const w = a[a.length - 1];
  return a.slice(-max).filter(x => akin(x, w)).length === 1
    && b.slice(0, MAX_LEAD + 1).filter(x => akin(x, w)).length === 1;
}

/**
 * Убрать из next то, что уже было сказано в конце prev.
 *
 * @param {string} prev текст предыдущего куска, как его выдала модель
 * @param {string} next текст куска, который начинается с перехлёста
 * @param {number=} repeat сколько секунд в начале next звучат второй раз, если
 *   это известно от того, кто их повторил. Сегментатор повторяет свои доли
 *   секунды всегда, и про них тут знают без подсказки; а вот быстрой модели в
 *   начало куска доклеивают секунду прошлого звука нарочно (DRAFT_CONTEXT_MS в
 *   offscreen.js) — в тексте следов этого нет, и сказать про это может только
 *   вызывающий. Повтор тогда и длиннее, и точно есть, и склейка ищет смелее.
 * @returns {string} next без повтора; пустая строка, если повтором было всё
 */
export function stitch(prev, next, repeat = 0) {
  return seam(prev, next, repeat).text;
}

/**
 * То же, что stitch, но вместе с расплатой: сколько слов в конце prev пришлось
 * списать на досочинённое, чтобы якорь нашёлся (MAX_SLACK выше).
 *
 * Эти слова — не речь, и оставлять их на экране незачем, но выбросить их может
 * только тот, у кого конец prev ещё не показан. Такой текст есть ровно один —
 * придержанный огрызок предложения (lib/carry.js), он и спрашивает seam.
 *
 * @returns {{text:string, slack:number}} text — next без повтора; slack — 0,
 *   если якорь нашёлся у самого обрыва или не нашёлся вовсе
 */
export function seam(prev, next, repeat = 0) {
  if (!prev || !next) return { text: next || '', slack: 0 };

  // Точка в конце предыдущего куска ничего не доказывает. Сюда попадают только
  // куски, которые сегментатор обрезал по таймеру посреди речи и специально
  // повторил долю секунды звука в следующем, — то есть про конец мысли уже
  // известно, что его там не было. Модель ставит точку всё равно: у обрыва она
  // не слышит продолжения и закрывает предложение сама.
  //
  // Раньше эта точка отменяла склейку целиком, и на трёхминутном ролике семь
  // реплик из сорока пяти начинались с повтора конца предыдущей: «…starting
  // with our first house.» ⇢ «First house in our neighborhood.», «…these houses
  // are built.» ⇢ «are built on a solid foundation». Все семь — после точки,
  // других не было вовсе.
  //
  // Но отменять запрет насовсем тоже нельзя: он ловил настоящую ошибку — на
  // «…they currently go to.» ⇢ «How many kids go to school in here?» якорем
  // становилось «go to», и вопрос лишался первых пяти слов. Разница между этими
  // случаями не в точке, а в том, где стоит якорь. Повтор в звуке лежит в самом
  // начале куска, поэтому и в тексте он начинается с первого слова. Якорь,
  // до которого модель успела сказать три своих слова, — это не шов, а
  // случайное совпадение словаря. Значит после точки ищем шов только с нулевого
  // слова, а всё остальное оставляем как есть.
  //
  // Всё это — про перехлёст, о котором известно только из текста. Когда звук
  // повторили нарочно и сказали, сколько его, гадать не о чем: повтор в начале
  // куска есть наверняка, и точка перед ним ничего не отменяет. Из прогона с
  // доклеенной секундой оба таких стыка потеряны молча: «…pour concrete like
  // this.» ⇢ «Free like this. That's awesome…», «…is 4 feet across.» ⇢ «It is
  // four feet across and we build…».
  const known = repeat >= KNOWN_SEC;
  const strict = !known && ENDED.test(prev.trim());

  const b = words(next);
  const { n, slack } = overlapWords(words(prev).map(norm), b.map(norm), overlapCap(repeat),
    strict ? STRICT_LEAD : MAX_LEAD, known ? MAX_SLACK : 0);
  return { text: b.slice(n).join(' '), slack };
}

/**
 * Обратная склейка: сколько слов надо срезать с конца prev, потому что next
 * начал пересказывать их заново.
 *
 * Это тот самый случай из заголовка — модель насочиняла в конце предыдущего
 * куска, якоря на самом стыке нет, и срезать начало следующего нельзя:
 *
 *   …every day. And now that the village is going to be
 *                ⇢ And now that, thankfully, flooding won't be an issue,
 *
 * Зато видно, где модель начала заново: «And now that» стоит и там, и там.
 * Всё, что предыдущий кусок наговорил после этого места, он наговорил без
 * звука — и это его и надо выбросить, а не начало следующего.
 *
 * Пользоваться этим можно только с текстом, который ещё не показали: отнимать
 * у зрителя уже прочитанное хуже любого дубля. Такой текст есть — придержанный
 * хвост незаконченного предложения (lib/carry.js).
 *
 * @returns {string} prev без пересказанного хвоста
 */
export function trimOverrun(prev, next) {
  const a = words(prev), na = a.map(norm), nb = words(next).map(norm);
  if (na.length < 2 || nb.length < 2) return prev;

  let best = { at: a.length, k: 1 };
  // Ищем по всему prev: окна тут не нужно, потому что prev — это придержанный
  // огрызок предложения, и весь он целиком стоит у самого обрыва.
  for (let i = 0; i < na.length - 1; i++) {
    let k = 0;
    while (k < nb.length && i + k < na.length && na[i + k] === nb[k]) k++;
    // Совпавшее слово посреди фразы — это словарь; пересказ начинается минимум
    // с двух, и чем он длиннее, тем он вернее. Из равных берём последний:
    // выбросить лишнее хуже, чем оставить лишнее.
    if (k > 1 && k >= best.k) best = { at: i, k };
  }
  return a.slice(0, best.at).join(' ');
}
