const listener = (msg, sender) => {
  if (!msg || typeof msg !== 'object') return;
  // Реплики и тики offscreen шлёт всем страницам расширения, и фон пересылает
  // их панели ещё раз, уже с настройкой showOriginal. Без этой проверки каждая
  // строка рисовалась дважды: сначала без оригинала, через миг с ним.
  if ((msg.type === 'CAPTION' || msg.type === 'LIVE_BEAT')
      && sender?.url?.endsWith('/offscreen.html')) return;
  // Сначала обычное состояние, потом просьба о словаре: у неё свой текст в
  // шапке, и показать его надо поверх, а не под.
  if (msg.type === 'STATUS_UPDATE') {
    if (msg.status?.stage === 'starting') renew();
    statusSeen = true;
    showStage(msg.status);
    return void showPack(msg.status?.pack);
  }
  // Захват начали не кнопкой, а кликом по иконке: панель открылась тем же
  // кликом и успела спросить состояние раньше, чем сеанс появился, — про него
  // ей говорят отдельно. Иначе кнопка осталась бы «Включить субтитры» при
  // идущих субтитрах, а настройки — доступными посреди сеанса.
  if (msg.type === 'CAPTIONS_ON') return void setRunning(true);
  // Субтитры выключили — ленту оставляем: её дочитывают уже после остановки.
  // Флажок нового клика мог прийти раньше этого сообщения (сеанс снял фон):
  // тогда он ждёт, пока панель не перестанет «слушать».
  if (msg.type === 'CAPTIONS_OFF') { setRunning(false); showStage(null); return void maybeAutostart(); }
  if (msg.type === 'CAPTION') take(msg);
  // Признак речи: ответа на него никто не ждёт, в ленту он не попадает.
  if (msg.type === 'LIVE_BEAT') hear(!!msg.voice);
};
chrome.runtime.onMessage.addListener(listener);

/**
 * Клик по значку расширения без идущего сеанса просит панель завести захват:
 * фоновый скрипт оставляет флажок autostart, а нажать «включить» (и погреть
 * словарь под жестом) может только сама страница панели. Жмём ту же кнопку,
 * что и человек. Флажок свежий — иначе это эхо прошлого клика, пережившее закрытие панели в session storage. Клик по значку
 * бывает и при уже открытой панели (сеанс кончился, панель осталась) — тогда
 * флажок приходит в onChanged, а не на загрузке; отсюда оба пути.
 */
//
// Один клик — один запуск: оба пути могут прочесть один и тот же флажок, пока
// его не стёрли, поэтому помним метку последнего. Прежде здесь стоял флажок
// «уже запускались» на всю жизнь панели — и после «выключить» следующий клик по
// значку при открытой панели не делал ничего.
let autostartedAt = 0;
// Конфиг из фона ещё не в форме: «включить» записало бы умолчания формы (цель
// en) поверх выбранного языка, и английское видео «переводилось» в английский.
let formReady = false;
async function maybeAutostart() {
  if (running || !formReady) return;
  // Окно — до флажка: прочитанный после await флажок мог смениться кликом в
  // другом окне, и эта панель стёрла бы чужой.
  const win = await chrome.windows?.getCurrent().then((w) => w.id, () => null);
  let flag = null;
  try { flag = (await chrome.storage.session.get('autostart')).autostart; } catch {}
  if (!flag || flag.at === autostartedAt) return;
  // Клик в другом окне — запуск его панели: и вкладка клика там же.
  if (flag.windowId != null && win != null && flag.windowId !== win) return;
  // Сеанс мог запуститься другим путём, пока ждали: «включить» его выключило бы.
  if (running) return;
  autostartedAt = flag.at;
  chrome.storage.session.remove('autostart').catch(() => {});
  // Минута, а не секунды: на слабой машине панель с холодным фоном грузится долго.
  if (Date.now() - flag.at > 60000) return;
  els.go.click();
}
chrome.storage.onChanged.addListener((ch, area) => {
  if (area === 'session' && ch.autostart?.newValue) maybeAutostart();
  // Offscreen мог услышать (другой) язык за текущий сеанс — держим свежим, чтобы
  // следующее включение погрело верный словарь.
  if (area === 'local' && ch.lastSource) lastSource = ch.lastSource.newValue || '';
  if (area === 'local' && (ch.strainAt || ch.strainShut)) void checkStrain();
});

// Панель открывают и до захвата, и во время него: состояние берём у фонового
// скрипта, а не ждём следующего сообщения.
const state = await chrome.runtime.sendMessage({ type: 'GET_STATE' }).catch(() => null);
if (state) {
  applyConfig(state.config);
  setRunning(state.running);
  showStage(state.status);
  void checkStrain();
  if (state.rows?.length) {
    for (const c of state.rows) {
      take({ phrase: c.from, endPhrase: c.to, line: c.line, growing: c.growing, open: c.open, cont: c.cont,
        lag: c.lag, translated: c.orig ? c.text : null, original: c.orig || c.text, partial: true });
    }
  } else if (state.lastCaption?.text || state.lastCaption?.translated || state.lastCaption?.original) {
    take({ ...state.lastCaption, partial: false });
  }
} else {
  // Фон не ответил: язык берём из storage, иначе select остаётся на первом
  // пункте (en), и первое же включение записало бы его поверх выбранного.
  const { config } = await chrome.storage.local.get('config').catch(() => ({}));
  if (config?.target) applyConfig({ source: 'auto', ...config });
}
// Загрузка или отказ пары из статуса offscreen — если свежий STATUS_UPDATE не
// пришёл раньше этого ответа (его pack новее).
if (state?.status?.pack && !statusSeen) showPack(state.status.pack);
// После того как узнали, идёт ли сеанс: если нет и значок оставил свежий
// флажок — запускаемся сами.
formReady = true;
maybeAutostart();

/** Ручка для отладки и для стенда: подать реплику, не дожидаясь речи. */
window.__captions = {
  take: listener,
  // Отказ перезапуска из графита (смена языка или устройства посреди сеанса).
  showError: (error) => showStage({ error }),
  show: (text, original = '', draft = false, meta = {}) => listener({
    type: 'CAPTION', partial: draft, open: draft, translated: text, original,
    showOriginal: !!original, phrase: meta.phrase ?? 0, endPhrase: meta.endPhrase ?? meta.phrase ?? 0,
    lag: meta.lag
  }),
  // Куда панель поставила прокрутку и следит ли она ещё за живой строкой.
  // Место живого текста — то, на что смотрят все три минуты, и разбирать его
  // съезды по одному DOM неудобно: цифры видны только здесь.
  where: () => ({
    page, rows: rowsEl.children.length, height: rowsEl.scrollHeight,
    client: view.clientHeight
  }),
  // Стереть ленту извне. Графит зовёт это, когда зритель меняет язык посреди
  // сеанса: offscreen перезапускается с новой парой, а строки прошлой цели
  // иначе остаются висеть и мешаются с новыми — на экране каша из двух языков.
  clear: clearCues,
  // Автосохранение (графит): sink получает каждую устоявшуюся строку один раз,
  // flush отдаёт и недоговорённые — перед закрытием панели.
  save: (fn) => { sink = fn; settle(); },
  flush: () => settle(true),
  // Ещё не отданные строки, живая в их числе: копия расшифровки берёт их как
  // есть, не отмечая отданными.
  pending: () => cues.filter((c) => !c.saved).map((c) => ({ text: c.text, orig: c.orig, at: c.at })),
  // Последние строки для плашки поверх страницы (графит, overlay.js).
  tail: (n = 2) => cues.slice(-n).map((c) => ({ id: c.from, text: c.text, orig: c.orig, open: !!c.open }))
};
