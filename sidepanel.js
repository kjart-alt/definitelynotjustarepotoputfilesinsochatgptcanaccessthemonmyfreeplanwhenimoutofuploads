// Где сейчас речь.
//
// Нижняя строка растёт на глазах, но читать её как «вот здесь говорят прямо
// сейчас» было нельзя: на экран идёт перевод, а переводчик недоговорённую
// фразу каждый раз уточняет заново. Замер на трёхминутном ролике — 301
// обновление живой строки: дописанной префиксом пришла 144, остальные 157
// переформулированы целиком, вплоть до заглавной буквы в первом слове
// («это колесо» → «Это колесо позади меня»). Строка от этого мигает вся
// сразу, и край речи глазом не находится.
//
// Поэтому край мы считаем сами и показываем его ярче остального: сравниваем
// с прошлым показом той же строки по словам, без учёта регистра и знаков, и
// подсвечиваем всё от первого расхождения. Заодно это видно и когда
// переводчик переписал середину — там подсветка расползается, и это правда
// о том, что произошло, а не украшение.
const KEY = (w) => w.toLowerCase().replace(/[.,!?;:—–…"'«»()]/g, '');
// Сколько слов подсвечивать самое большее. Переформулированная строка иначе
// загорается целиком, а «сейчас говорят» — это край, а не вся фраза.
const TIP_WORDS = 6;
let tip = { row: null, said: [] };
// Когда в последний раз переписали строку про скорость: чаще раза в 700 мс
// цифра только рябит.
let perfAt = 0;

/**
 * Написать в строку текст, подсветив край речи.
 * @param {HTMLElement} el строка ленты
 * @param {string} text что показать
 * @param {string} row опознавательный номер строки: подсветка считается
 *   относительно прошлого показа той же строки, а не соседней
 * @param {Uint8Array} marks что стало со словами строки (marksFor)
 */
function paint(el, text, row, marks) {
  const said = text.split(/\s+/).filter(Boolean);
  const prev = tip.row === row ? tip.said : [];
  let k = 0;
  while (k < prev.length && k < said.length && KEY(prev[k]) === KEY(said[k])) k++;
  tip = { row, said };
  // Хотя бы одно слово горит всегда: пока фраза не закрылась, речь идёт, и
  // показать это надо даже в тот заход, когда перевод не изменился вовсе.
  const from = Math.max(Math.min(k, said.length - 1), said.length - TIP_WORDS, 0);
  const head = said.slice(0, from).join(' ');
  const edge = said.slice(from).join(' ');
  if (el.dataset.edge === edge && el.dataset.head === head) return;
  el.dataset.head = head;
  el.dataset.edge = edge;
  wordsInto(el, said, from, marks);
}

// Сколько длится проявление слова. Короче 120 мс глаз его не замечает вовсе;
// при 170 на ядре процессора, где куски идут каждые 320 мс, слово вспыхивало,
// а не проявлялось. Наложиться двум проявлениям не страшно: у каждого слова своё.
const WORD_IN = 240;
// Кривая проявления: быстрый вход без рывка в первом кадре, долгий мягкий хвост.
const EASE = 'cubic-bezier(.3, .1, .2, 1)';
// Что стало со словом против прошлого показа реплики (marksFor).
const KEPT = 0, SWAPPED = 1, ADDED = 2;
/**
 * Сверить слова реплики с прошлым показом: какие остались, какие заменены,
 * какие дописаны.
 *
 * По общей подпоследовательности, а не по номеру места. По месту вставка
 * одного слова в середину сдвигала весь хвост, и каждое слово хвоста
 * считалось переписанным: на записанных прогонах так «переписывалось» вдвое
 * больше слов, чем менялось на деле, а строка целиком — от 21 до 46 раз за
 * три минуты вместо 1–17. Правка одних знаков и регистра («дом» → «Дом.»)
 * слово не меняет (KEY).
 *
 * Дописанное — то, что за последним оставшимся словом выходит дальше, чем
 * шёл за ним прошлый показ: первые слова после него заменяют прежний хвост.
 * Не по длине всего показа: верх реплики уходит за край окна или на прошлую
 * страницу, и дописанное в тот же кадр по длине читалось бы заменой.
 *
 * @param {string[]} prev слова прошлого показа
 * @param {string[]} next слова нынешнего
 * @returns {Uint8Array} по слову next: KEPT, SWAPPED или ADDED
 */
function marksFor(prev, next) {
  const a = prev.map(KEY), b = next.map(KEY), n = a.length, m = b.length;
  const out = new Uint8Array(m).fill(SWAPPED);
  // L[i][j] — длина общей подпоследовательности хвостов a[i:] и b[j:].
  const L = Array.from({ length: n + 1 }, () => new Uint16Array(m + 1));
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) L[i][j] = a[i] === b[j] ? L[i + 1][j + 1] + 1 : Math.max(L[i + 1][j], L[i][j + 1]);
  }
  let lastI = -1, lastJ = -1;
  for (let i = 0, j = 0; i < n && j < m;) {
    if (a[i] === b[j]) { out[j] = KEPT; lastI = i++; lastJ = j++; } else if (L[i + 1][j] >= L[i][j + 1]) i++; else j++;
  }
  for (let j = lastJ + 1 + (n - 1 - lastI); j < m; j++) out[j] = ADDED;
  return out;
}

/**
 * Разложить строку по словам, по узлу на слово, и проявить дописанные.
 *
 * Слово — отдельный узел не ради красоты: подсветку края речи раньше несла
 * одна общая обёртка, и всякая дописка переписывала её целиком. Проявлять
 * такую обёртку значило мигать всей фразой на каждом слове.
 *
 * Показанный текст не гаснет никогда. Проявляется из нуля только дописанное
 * (ADDED) — его на экране не было. Заменённое слово (SWAPPED) встаёт на место
 * сразу: прежде оно гасло до 0.35 и проявлялось заново, а переводчик
 * переписывает живую строку на каждом снимке, 3–5 раз в секунду, — строка
 * пульсировала, не успевая разгореться («мерцает, на миг текст исчезает»).
 * Где правка в живой строке, и так видно: край речи горит ярче (paint).
 * Подъём дописанных и доезд растолканных соседей (FLIP) сняты 0.5.2.99:
 * соседи ехали через перенос строки поверх новых слов и наползали на них.
 *
 * Пробелы — настоящими текстовыми узлами между словами, не через ::before:
 * textContent строки читают и стенд, и e2e, и склейка без пробелов молча
 * испортила бы весь счёт точности.
 *
 * @param {HTMLElement} el строка ленты
 * @param {string[]} said слова строки
 * @param {number} from с какого слова начинается край речи
 * @param {Uint8Array} marks что стало с каждым словом (marksFor)
 */
function wordsInto(el, said, from, marks) {
  // Строка могла быть написана цельным текстом (так пишутся договорённые) —
  // тогда узлов нет вовсе, и остаток надо убрать, иначе он уедет в начало.
  if (!el.children.length) el.textContent = '';
  while (el.children.length > said.length) {
    const last = el.lastElementChild;
    const sep = last.previousSibling;
    if (sep && sep.nodeType === 3) sep.remove();
    last.remove();
  }
  while (el.children.length < said.length) {
    if (el.children.length) el.append(document.createTextNode(' '));
    el.append(document.createElement('span'));
  }
  // Строка, которой на экране не было, проявляется целиком и сама
  // (.row.fresh). Проявлять в ней ещё и каждое слово значит наложить два
  // разных проявления с разной скоростью — выходит рябь на ровном месте.
  const show = !still.matches && !el.classList.contains('fresh');
  const changed = [];
  said.forEach((w, i) => {
    const node = el.children[i];
    const cls = i >= from ? 'w tip' : 'w';
    if (node.className !== cls) node.className = cls;
    if (node.textContent !== w) changed.push(i);
  });
  for (const i of changed) {
    const node = el.children[i];
    // В узле теперь другое слово: недоигранное проявление прежнего к нему
    // не относится, а то, что осталось или заменено, стоит в полную силу.
    for (const a of node.getAnimations()) if (a.id === 'w-in') a.cancel();
    node.textContent = said[i];
    if (show && marks?.[i] === ADDED) node.animate([{ opacity: 0 }, { opacity: 1 }], { id: 'w-in', duration: WORD_IN, easing: EASE });
  }
}

// Звук идёт прямо сейчас.
//
// Слово доходит до экрана за секунду, и всю эту секунду панель не показывала
// ничего: пока лента пуста, зритель не может отличить «считаю» от «сломалось»,
// и секунда на глаз вырастает в семь. Признак речи offscreen присылает с
// самого кадра, не дожидаясь ни распознавания, ни перевода, — это и есть
// нулевая задержка. Показываем его строкой на том месте, где встанет первое
// слово: слово её и заменит.
let voice = false;
let voiceTimer = null;
const hearEl = $('hear');
// Сколько отметка горит самое малое. Зажигалась она 23 раза за три минуты и
// держалась по 0.2 с — это не признак работы, а мерцание, и глаз за него
// цеплялся сильнее, чем за сам текст.
const HEAR_MIN = 900;
let hearSince = 0;
let hearTimer = null;

/**
 * Пришёл признак речи (или его отсутствие).
 * @param {boolean} on есть ли речь в самом свежем кадре
 * @param {boolean} [atOnce] гасить не дожидаясь, пока отметка отгорит своё
 */
function hear(on, atOnce = false) {
  voice = on;
  clearTimeout(voiceTimer);
  // Тики идут не реже, чем раз в 400 мс, пока захват жив. Пропали — значит
  // захват встал или вкладку сменили, и «распознаю» тогда врёт.
  if (on) voiceTimer = setTimeout(() => hear(false), 1400);
  // С какого мига слышим звук при идущем захвате — точка отсчёта для подсказки
  // о пустой ленте (см. STUCK_MS, слушаю()).
  if (on && running && !voiceFirstAt) voiceFirstAt = Date.now();
  // data-heard читает ui/graphite.js: речь слышна — крупное «ждём речь» врёт.
  set(document.body, 'heard', voiceFirstAt ? '1' : '');
  set(document.body, 'voice', on ? '1' : '');
  showHear(atOnce);
}

/**
 * Показать или спрятать «распознаю» — по речи и по тому, есть ли живая строка.
 * @param {boolean} [atOnce] гасить сразу, минуя наименьшее время горения
 */
function showHear(atOnce = false) {
  const last = cues.at(-1);
  // Живая строка сама показывает работу курсором, и вторая отметка под ней
  // читалась бы как ещё одна строка субтитров.
  const live = !!(last && (last.open || last.growing));
  // Про running не спрашиваем: тик приходит только пока offscreen считает
  // звук, и это и есть самый честный признак работы. Выключение гасит отметку
  // сразу, не дожидаясь, пока истечёт ожидание тика.
  const want = voice && !live;
  const shown = !hearEl.classList.contains('off');
  clearTimeout(hearTimer);
  if (want === shown) return;
  if (want) {
    hearSince = Date.now();
    hearEl.classList.remove('off');
    return;
  }
  const left = atOnce ? 0 : HEAR_MIN - (Date.now() - hearSince);
  if (left > 0) return void (hearTimer = setTimeout(() => showHear(), left));
  hearEl.classList.add('off');
}

// Сколько строк места держим под растущей живой репликой.
//
// Живая строка дописывается на глазах, и каждое слово в ней двигало всю ленту
// вверх; хуже того, перевод недоговорённой фразы больше чем в половине случаев
// приходит переписанным заново, то есть строка то удлиняется, то укорачивается,
// и текст дёргался туда-сюда по нескольку раз в секунду. Читать это нельзя.
// Поэтому под живой репликой держим пустое место: растёт она в эту пустоту, а
// начало её стоит на одной и той же высоте, и прочитанное выше не шевелится.
// Страница, а не лента на прокрутке.
//
// Написанное не двигается вовсе. Всякий сдвиг мешает читать сильнее самой
// задержки: строка растёт на глазах, перевод приходит переписанным заново (две
// правки из трёх — не дописка, а другая формулировка), и каждое такое
// обновление уводило уже прочитанное. Пробовали и держать место под живую
// строку, и показывать уезжание движением — на живом звуке текст всё равно
// съезжал по нескольку раз в секунду.
//
// Поэтому теперь так: текст пишется сверху вниз и стоит намертво, а когда место
// на странице кончилось — страница переворачивается целиком, и чтение идёт с её
// верха. Как в книге. Между переворотами не двигается ни одна строка.
// Это была страница. Сейчас пробуем обратно окно: лента прижата к нижней
// кромке, свежая строка встаёт снизу, прочитанное уползает за верхний край и
// там тает. Движение при этом неизбежно — в окне оно и есть формат, — поэтому
// всё, что раньше дёргалось, здесь сглажено: лента не прыгает на новую высоту,
// а доезжает до неё (slide), и слово не возникает, а проявляется (wordsInto).
// Страничный режим никуда не делся, он ниже целиком: переключается одной
// строчкой MODE, и обе ветки ходят через общий draw.
const MODE = 'книга';
const PAGE_FADE = 180;
// Сборка ui/: панель движется всегда. KDE с выключенными анимациями рабочего
// стола отдаёт Chromium «reduce», и лента тогда прыгала строками без всякого
// перехода, а плавность пользователь просил явно.
const still = { matches: false };

// Сколько времени лента проезжает половину оставшегося пути.
//
// Не длительность: обновления идут до пяти раз в секунду, и анимация с
// фиксированным концом не успевает доиграть до следующей — её приходилось бы
// обрывать, а обрыв и есть рывок. Поэтому сдвиг держим числом и каждый кадр
// приближаем к нулю: сколько бы правок ни пришло подряд, они складываются в
// одно непрерывное движение, и остановки между ними нет.
//
// Было затухание: сдвиг каждый кадр делился пополам за SLIDE_HALF. У него
// скорость наибольшая в самом первом кадре — лента с места срывалась, и на
// быстром ядре, где строки встают чаще, это и читалось рывком. Теперь пружина
// с критическим затуханием: скорость — часть состояния, разгон с нуля, новая
// строка посреди езды добавляет путь, но скорость не обрывает.
// SPRING — жёсткость в 1/мс: 95% пути за ~340 мс, как у прежнего затухания.
const SPRING = 0.014;
// Смещение ленты вниз от её настоящего места, пиксели. Ноль — доехала.
let shift = 0;
// Скорость ленты, пиксели в мс (к нулю — отрицательная).
let speed = 0;
let slideRaf = 0;
let slideAt = 0;

/**
 * Лента стала выше (или ниже) на d пикселей — проехать это расстояние, а не
 * перескочить. Сдвигаем на d вниз и тут же начинаем возвращать к нулю: глаз
 * видит, как прочитанное уезжает вверх, а новая строка поднимается снизу.
 * @param {number} d насколько изменилась высота ленты
 */
function slide(d) {
  if (still.matches || !d) return;
  shift += d;
  // Сдвиг — в этот же кадр: вёрстка уже новая, и кадр без него показал бы
  // ленту на новом месте, а следующий вернул бы на старое.
  rowsEl.style.transform = `translateY(${Math.round(shift * devicePixelRatio) / devicePixelRatio}px)`;
  if (slideRaf) return;
  slideAt = performance.now();
  slideRaf = requestAnimationFrame(slideStep);
}

function slideStep(ts) {
  // Кадр мог прийти с большим опозданием — машина была занята, вкладку
  // придержали. Считать затухание по настоящему промежутку в такой кадр значит
  // погасить сдвиг целиком за один раз, то есть показать ровно тот рывок,
  // ради которого всё это и заведено. Поэтому промежуток ограничен двумя
  // полупериодами: на редких кадрах лента доезжает за три-четыре кадра вместо
  // одного, на обычных ограничение не срабатывает вовсе.
  const dt = Math.min(Math.max(0, ts - slideAt), 48);
  // Точное решение пружины за dt: устойчиво при любом шаге кадра.
  const e = Math.exp(-SPRING * dt), k = speed + SPRING * shift;
  speed = (speed - SPRING * k * dt) * e;
  shift = (shift + k * dt) * e;
  slideAt = ts;
  if (Math.abs(shift) < 0.3 && Math.abs(speed) < 0.01) shift = speed = 0;
  // По целым пикселям экрана: пиксельный шрифт на дробном сдвиге мылится и
  // мерцает краями букв.
  const px = Math.round(shift * devicePixelRatio) / devicePixelRatio;
  rowsEl.style.transform = px ? `translateY(${px}px)` : '';
  slideRaf = shift ? requestAnimationFrame(slideStep) : 0;
}

/**
 * Верхний край окна режет ленту по строке, а не посреди буквы. Строку, у
 * которой верх ушёл бы за кромку, прячем целиком: на экране либо вся строка,
 * либо ничего — третьего не дано. Маской этого не снять и кратной высотой тоже:
 * строки разной высоты — длинную реплику переносит надвое, — границу знает лишь
 * замер каждой строки.
 *
 * Прячем прозрачностью, а не display: место строка держит, вёрстка не едет,
 * и отсчёты окна (places/lift меряют те же боксы) остаются верными. Нижнюю
 * (живую) строку не прячем никогда: окажись окно короче её — показать обрезок
 * честнее, чем погасить панель на том самом месте, где говорят сейчас.
 */
function clipTop() {
  // Судим по месту, где строка встанет, когда лента доедет (без shift): строка,
  // которой суждено уйти за кромку, начинает гаснуть сразу, пока ещё целиком в
  // окне, и к кромке подъезжает уже погасшей. Гаснет переходом (.row в
  // graphite.css), а не щелчком visibility.
  const top = view.getBoundingClientRect().top + shift;
  const kids = rowsEl.children;
  for (let i = 0; i < kids.length; i++) {
    const el = kids[i];
    const whole = i === kids.length - 1 || el.getBoundingClientRect().top >= top - 0.5;
    el.style.opacity = whole ? '' : '0';
  }
}

// С какой строки начинается нынешняя страница: номер фразы и часть реплики.
// Не индексом в ленте — точная модель склеивает по нескольку реплик в одну, и
// индексы от этого разъезжаются.
let page = null;

/** Показать, что страница перевернулась: проявлением, без всякого сдвига. */
function flip() {
  if (still.matches) return;
  for (const a of rowsEl.getAnimations()) a.cancel();
  rowsEl.animate([{ opacity: .25 }, { opacity: 1 }], { duration: PAGE_FADE, easing: 'ease-out' });
}

/**
 * Написать на странице ровно эти строки. Узлы переиспользуются: строка,
 * дописанная на месте, — та же строка, и заново её создавать нельзя, иначе
 * пропадёт и подсветка края речи, и само чувство, что текст стоит.
 */
let shown = new Map();
function draw(want) {
  // Сборка ui/: узлы — по строкам, а не по местам. Когда окно упирается в
  // ROWS, верхняя строка выпадает, и по местам каждый узел получал соседнюю
  // строку: вся лента считалась новой и проявлялась заново на каждой реплике.
  // Выкидываем узлы ушедших строк и вставляем пустые под пришедшие, тогда
  // «fresh» достаётся только тому, что на экране действительно появилось.
  const key = (el) => `${el.dataset.row}:${el.dataset.part}`;
  const keep = new Set(want.map((r) => `${r.cue.from}:${r.part}`));
  for (const el of [...rowsEl.children]) if (!keep.has(key(el))) el.remove();
  want.forEach((r, i) => {
    const el = rowsEl.children[i];
    if (!el || key(el) !== `${r.cue.from}:${r.part}`) rowsEl.insertBefore(document.createElement('div'), el ?? null);
  });
  while (rowsEl.children.length > want.length) rowsEl.lastElementChild.remove();
  while (rowsEl.children.length < want.length) rowsEl.appendChild(document.createElement('div'));
  // Что стало со словами, сверяем по реплике целиком, а не по строке: длинная
  // реплика режется на строки (lines), и шов между ними на живой реплике
  // ходит. Слова переезжают со строки на строку, а строка, которая то
  // появляется, то сливается с соседней, по строке выходила новой и
  // проявлялась целиком из нуля. shown — слова реплик в прошлом показе.
  const words = new Map();
  const at = want.map((r) => {
    const said = r.text.split(/\s+/).filter(Boolean);
    if (!words.has(r.cue.from)) words.set(r.cue.from, []);
    const all = words.get(r.cue.from);
    const off = all.length;
    all.push(...said);
    return { said, off };
  });
  const marks = new Map();
  for (const [k, all] of words) {
    const was = shown.get(k);
    marks.set(k, was && was.join(' ') !== all.join(' ') ? marksFor(was, all) : null);
  }
  want.forEach((r, i) => {
    const el = rowsEl.children[i];
    const m = marks.get(r.cue.from)?.subarray(at[i].off, at[i].off + at[i].said.length);
    const live = (r.cue.open || r.cue.growing) && i === want.length - 1;
    // «Появилась» — про строку, а не про узел. Узлы переиспользуются, и в
    // скользящем окне строка переезжает с узла на узел: окно выкинуло верхнюю
    // строку и добавило нижнюю — узлов столько же, но на последнем теперь
    // другая строка. Если считать появлением только новый узел, такая строка
    // возникнет без всякого проявления, зато wordsInto зажжёт в ней каждое
    // слово по отдельности. Узнаём строку по паре «реплика + часть»: она у
    // строки не меняется, пока строку дописывают. Проявляется целиком только
    // реплика, которой на экране не было: новая строка уже показанной реплики
    // несёт её же слова, и дописанные в ней проявит wordsInto.
    const same = el.dataset.row === String(r.cue.from) && el.dataset.part === String(r.part);
    const fresh = !same && !shown.has(r.cue.from);
    // Сборка ui/: проявление новой строки длиннее промежутка между
    // отрисовками, и снятый на следующей «fresh» обрывал его на полдороге.
    // Класс держим, пока проявление идёт.
    const showing = el.classList.contains('fresh') &&
      el.getAnimations().some((a) => a.animationName === 'show');
    el.className = `row${live ? ' open' : ''}${fresh || showing ? ' fresh' : ''}`;
    // Край речи подсвечиваем только в живой строке: в договорённых подсвечивать
    // нечего — там уже всё сказано, и лишняя яркость сбивала бы с толку.
    if (live) paint(el, r.text, `${r.cue.from}:${r.part}`, m);
    else if (el.textContent !== r.text) {
      // Договорённую строку тоже пишем словами, как живую: дописанное
      // проявляется, остальное стоит.
      const said = at[i].said;
      if (el.textContent !== said.join(' ')) wordsInto(el, said, said.length, m);
      delete el.dataset.head;
      delete el.dataset.edge;
    }
    // Номер фразы и отставание проставляем атрибутами на каждой строке. Это
    // видно в devtools на живой панели, и по этому же E2E строит таймлайн:
    // когда строка появилась и когда её переписала точная модель.
    set(el, 'phrase', String(r.cue.to));
    // Строка растёт на месте, и текст у неё каждый раз новый — узнать её по
    // тексту нельзя. Узнаётся она по фразе, с которой началась: та не меняется
    // ни когда строку дописывают, ни когда её переписывает точная модель.
    set(el, 'row', String(r.cue.from));
    // Какая это по счёту строка внутри реплики. Длинную реплику режут на
    // несколько, и без этого номера они неотличимы — а отличать их надо: по
    // паре «реплика + часть» окно узнаёт строку между двумя отрисовками и
    // считает, на сколько её подняло.
    set(el, 'part', String(r.part));
    set(el, 'lag', r.cue.lag == null ? '' : String(r.cue.lag));
    set(el, 'exact', r.cue.exact ? '1' : '');
    // Одна мысль — один абзац: вторая и дальше строка одной реплики, и первая
    // строка реплики, продолжающей предложение предыдущей, встают вплотную.
    set(el, 'join', r.part > 0 || r.cue.cont ? '1' : '');
    // Оригинал — той же частью реплики, что и строка перевода.
    const orig = r.cue.orig ? into(r.cue.orig, r.parts)[r.part] : '';
    set(el, 'orig', orig);
    origInto(el, orig);
  });
  shown = words;
}

/**
 * Оригинал над переводом — настоящим текстом в тени строки, а не ::before:
 * псевдоэлемент не выделяется и не копируется, а оригинал просили копировать
 * вместе с переводом. Тень, а не ещё один узел в строке: textContent строки —
 * перевод, по нему сверяют правки (draw, wordsInto) и считают точность стенды.
 * Выделение и копирование Chrome ведёт по составному дереву, тень в него
 * входит. Показ — body[data-orig] и ::part(og) в стилях.
 */
function origInto(el, orig) {
  let og = el.shadowRoot?.firstElementChild?.firstElementChild;
  if (!og) {
    if (!orig) return;
    const root = el.shadowRoot ?? el.attachShadow({ mode: 'open' });
    // Блок — место и отступ строки оригинала, строчный span внутри — фон
    // под каждой строкой текста (::part(ogt)), а не прямоугольник на всю ширину.
    const line = document.createElement('div');
    line.setAttribute('part', 'og');
    og = document.createElement('span');
    og.setAttribute('part', 'ogt');
    line.append(og);
    root.append(line, document.createElement('slot'));
  }
  if (og.textContent !== orig) og.textContent = orig;
}

function render() {
  if (MODE === 'окно') return renderWindow();
  if (MODE === 'книга') return renderBook();
  return renderPage();
}

/**
 * Стереть ленту перед новым сеансом. Без этого новый текст приклеивается к
 * старой строке: номера строк у нового сеанса начинаются заново (liveLine=0 в
 * offscreen), feed дописывает в ту же строку 0, и на экране выходит «…персонажа»
 * + «With Dopenarts» одной строкой. renderWindow на пустой ленте DOM не трогает
 * (возвращается сразу), поэтому чистим узлы руками.
 */
/**
 * Когда ленту стёрли последний раз. Стирают её перед каждым запуском и сменой
 * языка — раньше, чем offscreen начнёт новый сеанс, — и реплика, у которой
 * сеанс начат до стирания (since), принадлежит прошлому: её перевод ещё
 * шёл, когда зритель сменил пару, или она была в пути.
 */
let clearedAt = 0;
function clearCues() {
  clearedAt = Date.now();
  // Прежний сеанс дописываем в файл целиком, с живой строкой: дописывать её
  // больше некому.
  settle(true);
  sink?.(null);
  cues = [];
  page = null;
  shown = new Map();
  rowsEl.replaceChildren();
  origEl.textContent = '';
}

/**
 * Скользящее окно: показываем хвост ленты, прижатый к нижней кромке. Лишнее
 * уходит за верхний край и там гаснет маской — прокрутки нет и здесь, история
 * панели по-прежнему не хранится.
 *
 * Строки из ленты не выбрасываем по месту: сколько влезло, столько и видно, а
 * остальное обрезает .view. Считать влезающее в цикле, как это делает
 * страница, тут нельзя — высота меняется от каждого дописанного слова, и
 * пересчёт сам стал бы источником дёрганья.
 */
function renderWindow() {
  const all = visible(cues, ROWS);
  if (!all.length) return;
  const was = places();
  draw(all);
  slide(lift(was, places()));
  clipTop();
  const last = all.at(-1);
  origEl.textContent = last.cue.orig ? into(last.cue.orig, last.parts)[last.part] : '';
}

/**
 * Книга: строки пишутся сверху вниз и стоят на месте, лента прижата к верху
 * (.view в сборке ui/). Дошло до низа — прочитанное уезжает вверх на половину
 * окна одним доездом (slide), и письмо продолжается с середины. Скользящее
 * окно двигало текст на каждой строке, и читать на ходу было трудно.
 *
 * Начало страницы держим тем же page, что и у страничного режима.
 */
function renderBook() {
  const all = visible(cues, ROWS);
  if (!all.length) return;
  let start = 0;
  if (page) {
    const at = all.findIndex(r => r.cue.from > page.from || (r.cue.from === page.from && r.part >= page.part));
    start = at < 0 ? all.length - 1 : at;
  }
  const was = places();
  draw(all.slice(start));
  // Низ — по курсору «слышу»: он стоит под строками и место держит всегда.
  const vr = view.getBoundingClientRect();
  const room = vr.bottom - parseFloat(getComputedStyle(view).paddingBottom);
  const end = hearEl.getBoundingClientRect().bottom;
  if (end > room + 0.5 && start < all.length - 1) {
    // Сверху уходит столько строк, чтобы оставшееся заняло не больше половины.
    const half = (room - vr.top) / 2;
    const kids = rowsEl.children;
    let k = 1;
    while (k < kids.length - 1 && end - (kids[k].getBoundingClientRect().top - shift) > half) k++;
    start += k;
    draw(all.slice(start));
  }
  page = { from: all[start].cue.from, part: all[start].part };
  slide(lift(was, places()));
  const last = all.at(-1);
  origEl.textContent = last.cue.orig ? into(last.cue.orig, last.parts)[last.part] : '';
}

/**
 * Где сейчас стоит каждая строка — расстоянием от низа ленты, а не от верха.
 *
 * От низа потому, что лента прижата к нижней кромке: строка, выпавшая сверху,
 * на место остальных не влияет вовсе, а вот всякая прибавка снизу поднимает
 * их все. Мерим вёрсткой (offsetTop), а не экраном: экранные отсчёты во время
 * езды показывают ленту на полпути, и следующий сдвиг считался бы от
 * недоехавшего места.
 *
 * @returns {Map<string, number>} «реплика:часть» → сколько пикселей под ней
 */
// Где стоит каждая строка — считаем от окна, а не от самой ленты.
//
// От нижней кромки ленты считать проще, и долго так и считали, но тогда не
// видно целого класса рывков: кромка уезжает сама. Под лентой живёт и строка
// оригинала, и счётчик отставания, и всякий раз, когда там прибавляется
// линия, окно ленты становится на эти 18 пикселей ниже — и всё прочитанное
// дёргается вверх. Относительно собственной кромки при этом не сдвинулось
// ничего, и панель такой рывок просто не замечала: в прогоне на полминуты
// таких набралось 93 при нуле «законных» перескоков.
//
// Отсчёт от окна это ловит, но в него входит и сдвиг, который лента несёт
// прямо сейчас, — его вычитаем, иначе недоехавшее движение сложилось бы само
// с собой. Так места выходят такими, какими станут, когда лента успокоится.
function places() {
  const out = new Map();
  const base = innerHeight;
  for (const el of rowsEl.children) {
    const k = `${el.dataset.row}:${el.dataset.part}`;
    // По верху строки, а не по низу: живая строка, перенесясь на вторую
    // линию, растёт вверх от прижатого низа, и по низу её подъёма не видно —
    // верх с прочитанным прыгал на строку без всякой езды.
    if (!out.has(k)) out.set(k, base - (el.getBoundingClientRect().top - shift));
  }
  return out;
}

/**
 * На сколько подняло прочитанное.
 *
 * Считать по общей высоте ленты нельзя: как только окно упёрлось в ROWS,
 * каждая новая строка выталкивает сверху старую, высота не меняется ни на
 * пиксель — а весь текст при этом уезжает на строку вверх. Так и выходил
 * рывок: панель его просто не замечала.
 *
 * Поэтому считаем по строке, пережившей отрисовку, и берём самую верхнюю из
 * них: двигаться не должно прочитанное, а оно наверху. Нижняя строка к кромке
 * приклеена по построению, и по ней подъёма не видно вовсе.
 *
 * @returns {number} пиксели, на которые надо сдвинуть ленту вниз, чтобы
 *   прочитанное осталось там, где его читали
 */
function lift(was, now) {
  for (const [k, before] of was) {
    const after = now.get(k);
    if (after != null) return after - before;
  }
  return 0;
}

function renderPage() {
  const all = visible(cues, ROWS);
  if (!all.length) return;
  // Где начинается страница. Её начало могло уехать из памяти или попасть под
  // правку точной модели — тогда берём ближайшую к нему строку из тех, что есть.
  let start = 0;
  let turned = false;
  if (page) {
    const at = all.findIndex(r => r.cue.from > page.from || (r.cue.from === page.from && r.part >= page.part));
    start = at < 0 ? all.length - 1 : at;
    // Начала страницы в ленте больше нет — страница съехала не потому, что
    // место кончилось. Показать это надо тем же проявлением: рывок на ровном
    // месте читается как дрожь, и именно им он на замере и был.
    if (at < 0 || all[at].cue.from !== page.from || all[at].part !== page.part) turned = true;
  }
  for (;;) {
    draw(all.slice(start));
    if (rowsEl.scrollHeight <= view.clientHeight || start >= all.length - 1) break;
    // Место кончилось. Новая страница начинается с той реплики, которую читают
    // прямо сейчас: недоговорённую фразу рвать посередине незачем, её ещё
    // дописывают. Не влезла и она одна — тогда со следующей её строки, и
    // продолжение уходит на новую страницу, как в книге.
    //
    // И вместе с ней — те строки перед ней, которые точная модель ещё не
    // переписала. Она отстаёт от живой примерно на окно, и последние строки
    // страницы всегда ждут её правки; переворот уносил их черновыми, и правка
    // приходила в пустоту. В замере таких строк было шесть из двадцати шести
    // прочитанных — 13.6% текста, который зритель прочитал черновиком, хотя
    // точный пришёл через полсекунды-семь секунд после переворота.
    start = nextPage(all, start);
    turned = true;
  }
  page = { from: all[start].cue.from, part: all[start].part };
  if (turned) flip();
  const last = all.at(-1);
  origEl.textContent = last.cue.orig ? into(last.cue.orig, last.parts)[last.part] : '';
}

// Субтитры в этом сеансе уже пошли — значит «готовлюсь…» шапке говорить больше
// не о чем: запоздалый stage 'loading' откатывал бы её назад, будто расширение
// сбросилось и начало заново. А вот полосу загрузки с подписью «качаю модель»
// это не трогает: по ней видно, что веса едут.
let пошлиСубтитры = false;
// Модель доложила «готов» (или уже пошли субтитры). Пока нет — пустая лента
// значит «ещё гружусь», а не «язык не разобрал»: подсказку про язык до этого
// давать нельзя, а надо показывать значок загрузки.
let modelReady = false;
// Последний статус от offscreen: подсказку о «пустой ленте» надо перерисовывать
// по таймеру, а не только на новое сообщение (во время ровного «слушаю» их нет).
let lastStatus = null;
// Под «определить сам» слот 101 на сложном звуке (музыка, сильный шум) глотает
// речь целиком: звук громкий, «распознаю» горит, а лента пуста — и панель
// выглядит сломанной. Засекаем, с какого мига слышим звук; если за это время не
// пришло ни одной реплики, подсказываем выбрать язык руками, а не висим мёртвой
// пустотой. Порог с запасом на разогрев модели и первую фразу.
const STUCK_MS = 9000;
// Под явным языком сделать зрителю нечего: язык назван, звук идёт. Подсказка
// там лишь о том, что захват жив, а слов нет, и на песне с долгим вступлением
// через 9 с она читалась ошибкой (Apple Music, 18.10). Ждём дольше вступления.
const STUCK_NAMED_MS = 30000;
let voiceFirstAt = 0;
let stuckTimer = null;
// Миг, с которого модель готова и пошёл захват. Даже на тёплой модели первая
// строка приходит не сразу (~4–5 с): конвейер наполняется, первый проход по
// видеокарте греется. Всё это время лента пуста — и без значка это читается как
// «сломалось». Держим значок первые SETTLE_MS захвата (а если слышим речь — пока
// её не расшифруем). На тихой вкладке дальше не висим: шапка скажет «слушаю».
let capAt = 0;
const SETTLE_MS = 6000;

// Застряли: звук слышим давно, слов нет — И модель при этом уже готова. Пока
// она грузит веса, пустая лента — это «ещё гружусь» (об этом говорит индикатор
// загрузки), а не «язык не разобрал»; подсказку про язык до готовности не даём,
// иначе на большом первом скачивании зритель читал бы «не могу определить язык»,
// хотя идёт загрузка. И отсчёт тоже с готовности (capAt), а не с первого звука:
// звук слышен с самого включения, и после загрузки дольше порога шапка сразу за
// ready объявляла речь музыкой, хотя первая строка ещё просто не успела.
const stuckNow = () => running && !пошлиСубтитры && modelReady
  && voiceFirstAt && Date.now() - Math.max(voiceFirstAt, capAt)
    > (els.source.value === 'auto' ? STUCK_MS : STUCK_NAMED_MS);

// Машина не тянет: очередь звука переполнилась и звук выброшен (strainAt пишет
// фон по сигналу offscreen).
// Плашка висит, пока зритель её не закроет (strainShut пишет ui/graphite.js)
// или не начнётся новый сеанс (фон стирает strainAt в begin).
async function checkStrain() {
  const { strainAt = 0, strainShut = 0 } = await chrome.storage.local.get(['strainAt', 'strainShut']).catch(() => ({}));
  document.body.toggleAttribute('data-strain', strainAt > strainShut);
}

/** Шапка: одна строка о том, живы ли субтитры и чем они сейчас заняты. */
function showStage(s) {
  // Единица измерения идёт отдельным узлом: шапка написана строчными, и «мб»
  // в ней читается опечаткой, а не стилем.
  const say = (text, kind = '', unit = '') => {
    // Шапку перерисовывает и таймер раз в 2.5 с, и каждое состояние: тот же
    // текст не трогаем, иначе каждая запись будила наблюдателей графита
    // (paint) и пересчёт раскладки панели.
    const was = stage.querySelector('.unit')?.textContent ?? '';
    if (stage.textContent !== (unit ? `${text} ${unit}` : text) || was !== unit) {
      stage.textContent = text;
      if (unit) {
        const u = document.createElement('span');
        u.className = 'unit';
        u.textContent = unit;
        stage.append(' ', u);
      }
    }
    const cls = `head${kind ? ' ' + kind : ''}`;
    if (head.className !== cls) head.className = cls;
  };
  const слушаю = () => {
    // Подсказки помечены классом hint: графитовая шапка (ui/graphite.js)
    // показывает текст стадии только у ошибок и у них.
    // Слышим звук давно, а в ленте по-прежнему пусто — язык не определился
    // (чаще всего «определить сам» на музыке/шуме). Вместо мёртвой пустоты —
    // что делать: под «авто» назвать язык руками; под явным слотом это, скорее
    // всего, не речь.
    if (stuckNow()) {
      return say(els.source.value === 'auto'
        ? t('hintDetect')
        : t('hintNoise'), 'busy hint');
    }
    return say('listening to this tab', 'live');
  };
  lastStatus = s;
  els.bar.classList.remove('on');
  if (!s || s.stage === 'idle' || s.stage === 'starting') { пошлиСубтитры = false; voiceFirstAt = 0; modelReady = false; capAt = 0; set(document.body, 'heard', ''); }
  // capturing приходит и на холодном старте — раньше, чем воркер начнёт грузить
  // модель. Стадии загрузки готовность снимают: иначе порог «нет речи» шёл от
  // начала захвата, и сразу за ready шапка объявляла речь музыкой.
  if (s && (s.stage === 'loading' || s.stage === 'downloading')) { modelReady = false; capAt = 0; }
  if (s && (s.stage === 'ready' || s.stage === 'capturing')) { if (!modelReady) capAt = Date.now(); modelReady = true; }
  paintLoader();
  const off = () => say('subtitles off');
  if (!s) return off();
  if (s.error) return say(s.error, 'bad');
  if (s.download && s.download.total) {
    const mb = (n) => (n / 1048576).toFixed(0);
    const { loaded, total, file } = s.download;
    els.bar.classList.add('on');
    // Полоса одна: пока видно кольцо словаря, её ведёт он (fillPart).
    if (els.pack.hidden || els.pack.dataset.fail) els.fill.style.width = Math.round(loaded / total * 100) + '%';
    return say(`${s.download.cached ? 'loading model' : 'downloading model'}: ${file} · ${mb(loaded)} / ${mb(total)}`, 'busy', 'MB');
  }
  if (пошлиСубтитры) return слушаю();
  if (s.stage === 'loading' || s.stage === 'starting') return say('loading…', 'busy');
  if (s.stage === 'ready' || s.stage === 'capturing') return слушаю();
  off();
}

// Значок загрузки — по центру ленты, ровно там, где зритель ждёт субтитры.
//
// Прогрев бывает только на ПЕРВОМ включении за сессию: дальше модель остаётся
// тёплой в offscreen (см. scheduleColdClose в background.js), и этот значок
// мелькает доли секунды или не появляется вовсе. Но пока веса едут и собираются
// сессии, лента пуста — и без знака это читается как «сломалось». Рисуем его
// сами, а не в разметке: у стендовой и графитовой панели она разная, а узел
// нужен в обеих.
let loadEl = null;
function loader() {
  if (loadEl) return loadEl;
  loadEl = document.createElement('div');
  loadEl.className = 'loading';
  loadEl.setAttribute('aria-hidden', 'true');
  const spin = document.createElement('div');
  spin.className = 'spin';
  for (let i = 0; i < 4; i++) spin.appendChild(document.createElement('b'));
  const msg = document.createElement('div');
  msg.className = 'msg';
  loadEl.append(spin, msg);
  view.appendChild(loadEl);
  return loadEl;
}
/**
 * Показать/скрыть значок загрузки. Виден всё время от включения до первой строки
 * (пока модель грузится ИЛИ конвейер наполняется) — чтобы пустая лента не читалась
 * как «сломалось». НЕ виден, когда субтитры уже пошли, когда застряли на языке
 * (stuckNow: там своя подсказка в шапке) или встала ошибка (её тоже показывает
 * шапка). На тихой вкладке гаснет через SETTLE_MS — дальше говорит шапка «слушаю».
 */
function paintLoader() {
  const s = lastStatus;
  const el = loader();
  if (!running || пошлиСубтитры || stuckNow() || (s && s.error))
    return void el.classList.remove('on');
  // Модель не готова — всегда держим (бывает лишь на первом включении за сессию).
  // Модель готова, но ленты нет — первые SETTLE_MS захвата или пока слышим речь и
  // ждём её расшифровку. Иначе (тихая вкладка, время вышло) — гасим.
  const settling = capAt && Date.now() - capAt < SETTLE_MS;
  if (modelReady && !settling && !voiceFirstAt)
    return void el.classList.remove('on');
  // Первое скачивание весов разовое и долгое — так и говорим, чтобы зритель не
  // ждал этого каждый раз. Пока веса/сессии едут — «загружаю»; когда модель уже
  // тёплая и идёт прогрев конвейера — «запускаю».
  // Чтение весов из кеша (cached: true в weights.js) тоже идёт полосой, но это
  // не скачивание: при каждом запуске «Downloading model…» пугало.
  el.querySelector('.msg').textContent =
    t(s && s.download && s.download.total && !s.download.cached ? 'dlModel'
    : !modelReady ? 'loading'
    : 'starting');
  el.classList.add('on');
}

/**
 * Реплика от offscreen. Пришла она через фоновый скрипт, и поля у неё те же,
 * что у ленты: from/to — номера фраз, line — строка, которую быстрая модель
 * дописывает, partial — текст, который ещё перепишет точная.
 */
function take(msg) {
  if (msg.since && msg.since < clearedAt) return false;
  const ph = msg.phrase ?? 0;
  // Слитый кусок накрывает несколько фраз, и считается он по последней.
  const end = msg.endPhrase ?? ph;
  const cue = {
    from: ph, to: end, line: msg.line ?? null, growing: !!msg.growing,
    text: msg.translated || msg.original,
    // Оригинал держим всегда, а показывает его галка (body[data-orig]): включённая
    // посреди сеанса, она сразу находит его и у прочитанных строк.
    orig: msg.translated ? msg.original : '',
    open: !!msg.open, exact: !msg.partial, lag: msg.lag,
    // Строка продолжает предложение предыдущей (её резали посреди мысли).
    cont: !!msg.cont
  };
  if (!(msg.partial ? feed(cues, cue) : fix(cues, cue))) return false;
  // Время строки — миг первого показа. Растущая строка его не меняет: в cue
  // поля at нет, и Object.assign в feed его не трогает.
  const now = Date.now();
  for (let i = Math.max(0, cues.length - 2); i < cues.length; i++) cues[i].at ??= now;
  settle();
  // С этого мига шапке нечего обещать: субтитры идут, и чужая загрузка
  // перебивать их не должна. Значок загрузки гасим — модель явно готова.
  пошлиСубтитры = true;
  modelReady = true;
  paintLoader();
  render();
  // Слово приехало — отметку убираем сразу, не додерживая: она именно его и
  // замещала, пока его считали.
  showHear(true);
  // Скорость считаем по чистовому проходу: черновик по устройству быстрее, и
  // мерить по нему — обманывать себя. На первом месте отставание от речи:
  // именно его человек и замечает, а RTF — уже объяснение, почему так.
  if (!msg.partial && msg.ms != null) {
    const lag = msg.lag == null ? '' : `lag ${(msg.lag / 1000).toFixed(1)} s · `;
    els.perf.textContent = `${lag}recognized in ${msg.ms} ms, RTF ${msg.rtf}`
      + (msg.rtf > 1 ? '. Slower than real time, try a lighter model' : '');
    perfAt = Date.now();
  } else if (msg.partial && msg.lag != null && Date.now() - perfAt > 700) {
    // Отставание живой строки показываем прямо в панели. Без цифры про задержку
    // спорить нечем: на глаз она оценивается втрое больше, чем есть, — тем
    // сильнее, чем чаще строку переписывают.
    els.perf.textContent = `lag ${(msg.lag / 1000).toFixed(1)} s`;
    perfAt = Date.now();
  }
  return true;
}

