/**
 * Словарь Chrome здесь, под жестом кнопки, — в форке без Translator в воркере.
 * Правила те же, что у createPack в background.js (cutCreate), но
 * сеть — своя: срез — и offline панели.
 */
async function panelPack(from, to) {
  const pair = { sourceLanguage: from, targetLanguage: to };
  // create() сразу: жест живёт секунды. Сеть — по молчанию загрузки (cutCreate).
  let off = null;
  const t = await cutCreate(Translator, pair, {
    hold: (look) => {
      if (off) removeEventListener('offline', off);
      off = look;
      if (look) addEventListener('offline', look);
    }
  });
  t.destroy?.();
}

/**
 * Словарь Chrome через фон (workerPack). В фоновом воркере форка API нет: тот
 * же переводчик Chrome качает пару здесь, под жестом кнопки. Без жеста
 * (прогрев пар, warmPairs) create() отвечает NotAllowedError — нужен клик, так
 * велит Chrome: ошибка с повтором.
 */
async function packFromWorker(from, to) {
  // Жест надо взять до первого await: после ответа воркера его уже нет.
  const gesture = !!navigator.userActivation?.isActive;
  if (await workerPack(from, to)) return;
  if (!gesture) {
    // Скачать без жеста нельзя, но докачать мог другой (брошенный panelPack).
    if (await canPair(Translator, { sourceLanguage: from, targetLanguage: to }) === 'available') return;
    throw new Error('no Translator');
  }
  await panelPack(from, to);
}

/**
 * Пары, которые качает сама панель (warmTranslator): ключ → обещание. Их
 * кольцо не гасит чужой статус без пары, а сбой — устаревший статус.
 */
const mine = new Map();

// Ход загрузки каждой пары: доля — большая из двух словарей (race шлёт доли
// обоих вперемешку) — и «докачана» (at — когда). Кольцо рисуется с доли своей
// пары (полосу оно делит с моделью речи) и назад не едет. После «докачана» ход
// — от проигравшего гонки: мимо. «Качается» старше «докачана» — запоздалый
// статус (offscreen ещё собирает пару), новее — новая загрузка (сломался
// Chrome, стёрта подпара).
const parts = new Map();
const partOf = (from, to) => parts.get(from + '>' + to) || { part: 0, done: false };
const fillPart = (from, to) => { els.fill.style.width = Math.round(partOf(from, to).part * 100) + '%'; };

// Ход загрузки пары, которую качает другая страница расширения (обычно
// offscreen: язык речи узнан посреди ролика) — та же полоса.
onProgress((p) => {
  const k = p.from + '>' + p.to, e = parts.get(k) || { part: 0, done: false };
  if (!e.done && p.done) Object.assign(e, { part: 1, done: true, at: p.at || Date.now() });
  else if (!e.done && p.loaded != null) e.part = Math.max(e.part, p.loaded);
  parts.set(k, e);
  const b = els.pack;
  if (b.hidden || b.dataset.from !== p.from || b.dataset.to !== p.to) return;
  // Движок Firefox ждёт сети: «нет интернета», пока загрузка не пойдёт дальше.
  if (p.offline) {
    if (!b.dataset.fail) paintFailed(p.from, p.to, 'offline');
    return;
  }
  if (b.dataset.fail) {
    // Пару с отказом всё же докачали (оборванную Chrome докачал сам, Retry в
    // другой странице): ошибка больше не правда, и в общем статусе тоже.
    if (p.done) {
      b.hidden = true;
      delete b.dataset.fail;
      chrome.runtime.sendMessage({ type: 'ASR_STATUS', pack: null }).catch(() => {});
      return;
    }
    // Сеть вернулась, загрузка идёт дальше — снова кольцо, с её долей.
    if (p.loaded == null || b.dataset.fail !== 'offline') return;
    showPack({ from: p.from, to: p.to, can: 'downloading' });
  }
  // Пара на месте: кольцо полное, даже если Chrome последнего хода не прислал.
  if (p.loaded != null || p.done) fillPart(p.from, p.to);
});

// Язык прошлого сеанса (offscreen→background→storage): под «авто» греем его
// словарь, а не только английский. Держим в переменной, чтобы на клике жест не
// тратился на await storage.
let lastSource = '';
chrome.storage.local.get('lastSource').then(r => { lastSource = r.lastSource || ''; }).catch(() => {});
// Язык, который offscreen расслышал в этом сеансе: смена цели посреди сеанса
// качает именно его пару, а не слепой en.
chrome.storage.onChanged.addListener((ch, area) => {
  if (area === 'local' && ch.lastSource) lastSource = ch.lastSource.newValue || '';
});

/**
 * Какие пары скачать заранее. Явный источник — его одну. Под «авто» язык речи
 * ещё неизвестен, поэтому качаем самые вероятные: язык прошлого сеанса и
 * английский. У вернувшегося зрителя одна из них обычно уже на диске.
 */
function warmPairs(config) {
  // Зритель выбрал другой язык: ошибка прошлой пары больше не про него. Снимаем
  // и из общего статуса, иначе первый же STATUS_UPDATE принёс бы её назад.
  if (els.pack.dataset.fail) {
    els.pack.hidden = true;
    delete els.pack.dataset.fail;
    chrome.runtime.sendMessage({ type: 'ASR_STATUS', pack: null }).catch(() => {});
  }
  const srcs = config.source === 'auto'
    ? [lastSource, mtCode('en')].filter(Boolean)
    : [mtCode(config.source)];
  const quiet = config.source === 'auto';
  const seen = new Set();
  const warm = [];
  for (const mt of srcs) {
    if (!mt || mt === mtCode(config.target) || seen.has(mt)) continue;
    seen.add(mt);
    warm.push(warmTranslator(mt, mtCode(config.target), quiet));
  }
  return Promise.all(warm);
}

/**
 * Скачать определитель языка Chrome, пока жест зрителя ещё действует.
 *
 * Нужен он только под «авто» и только offscreen: тот спрашивает его по первым
 * словам живой строки и так узнаёт язык речи раньше, чем модель напечатает
 * метку. Необязательно и молча: не скачался — субтитры идут как раньше.
 */
async function warmDetector() {
  const API = self.LanguageDetector;
  if (!API) return;
  try {
    if (await API.availability() === 'available') return;
    // Как и у словаря: скачивание требует живого жеста, которого на автозапуске
    // со значка нет — определитель уже качает SW (warmPacks). Без жеста уходим.
    if (!navigator.userActivation?.isActive) return;
    const d = await API.create();
    d.destroy?.();
  } catch (e) { /* не скачался — язык скажет модель, только позже */ }
}

