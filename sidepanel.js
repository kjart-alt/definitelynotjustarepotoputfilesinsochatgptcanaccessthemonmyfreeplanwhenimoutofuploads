/**
 * Скачать пару перевода заранее, пока захват поднимается.
 *
 * Словарь Chrome качает фоновый скрипт (WARM_PACK): в воркере жест не нужен, и
 * загрузка пары одна на всех — панель, offscreen и клик по значку ждут одну и
 * ту же. Модели Firefox качаются здесь же. Ход загрузки — в полосе (кольцо
 * графита, onProgress), сбой — ошибка с кнопкой повтора (paintFailed).
 * quiet — догадка под «авто»: её сбой ни о чём не говорит, язык речи может
 * оказаться другим, и тогда пару спросит offscreen.
 *
 * Своя загрузка пары одна: повтор той же пары (кнопка) ждёт идущую.
 *
 * @returns {Promise<boolean>} пара на месте
 */
function warmTranslator(source, target, quiet = false) {
  if (!source || source === target) return Promise.resolve(true);
  const key = source + '>' + target;
  if (quiet) return warmPair(source, target, true);
  // Пара уже качается (bergamot ждёт сети), а зритель жмёт Retry: под этим
  // жестом снова просим словарь Chrome — он мог отказать без сети.
  if (mine.has(key)) {
    if (Translator.gesture) packFromWorker(source, target).catch(() => {});
  } else mine.set(key, warmPair(source, target, false).finally(() => mine.delete(key)));
  return mine.get(key);
}

async function warmPair(source, target, quiet) {
  const pair = { sourceLanguage: source, targetLanguage: target };
  const can = await canPair(Translator, pair);
  const refuse = () => {
    if (!quiet) {
      showStage({ error: t('mtNo', { a: source, b: target }) });
      // Прежний сбой пары в общем статусе (offline, failed) больше не правда.
      chrome.runtime.sendMessage({ type: 'ASR_STATUS', pack: null }).catch(() => {});
    }
    return false;
  };
  // Пару не знает (или молчит) Chrome — может знать bergamot: спросим его
  // гонкой ниже; Chrome при этом всё равно пробуем, фон спросит его сам.
  const no = can === 'unavailable' || can === 'failed';
  if (no && !Translator.gesture) return refuse();
  // Словарь Chrome готов: остаток bergamot стёр сам ответ (Translator.availability).
  if (can === 'available') return true;
  // Без сети «нет интернета» скажет загрузчик: движок Firefox — в канале,
  // пока ждёт её, словарь Chrome — ответом фона.
  // Кольцо — только пока что-то качается (downloads, как ring в offscreen).
  const wait = await downloads(pair, can !== 'unavailable');
  if (!quiet && wait) showPack({ from: source, to: target, can: 'downloading', at: Date.now() });
  let ok = false;
  try {
    // Словарь Chrome и bergamot пары качаются оба (race): кольцо гаснет, как
    // только готов любой — переводит тогда он, а Chrome докачивает фоном.
    // Панель не переводит: свою сессию bergamot отпускает сразу, иначе её
    // замок не дал бы удалить словарь, когда Chrome готов.
    if (Translator.gesture) {
      (await race(pair, () => packFromWorker(source, target))).ff?.destroy();
    } else {
      // Ход загрузки — через onProgress, как у гонки: кольцо назад не едет.
      (await Translator.create(pair)).destroy?.();
    }
    ok = true;
    return true;
  } catch (e) {
    // Не вышло у обоих, а Chrome пары не знает — «пары нет», как без гонки.
    if (no) return refuse();
    // Пока качали, зритель выбрал другой язык: сбой старой пары уже не про него.
    // Сбой — в общий статус: по нему ошибку видит и панель, открытая заново, и
    // снимает её статус без пары (offscreen докачал пару сам, новый сеанс).
    if (!quiet && chosenPair(source, target)) {
      const can = packFailure(e);
      paintFailed(source, target, can);
      chrome.runtime.sendMessage({ type: 'ASR_STATUS', pack: { from: source, to: target, can } }).catch(() => {});
    }
    return false;
  } finally {
    // Кольцо этой пары гасим сами (и докачанной, и брошенной сменой цели):
    // статус без пары, который его снял бы, мог прийти, пока пара ещё
    // качалась, и больше не прийти до конца сеанса.
    if (!quiet) {
      const b = els.pack;
      // Докачалась — гасим и «нет интернета», которое ставил offline посреди загрузки.
      if ((ok || !b.dataset.fail) && b.dataset.from === source && b.dataset.to === target) {
        b.hidden = true;
        delete b.dataset.fail;
      }
    }
  }
}

// Пара из выбранных сейчас языков. Под «авто» язык речи не выбран: годится любой.
function chosenPair(source, target) {
  return mtCode(els.target.value) === target
    && (els.source.value === 'auto' || mtCode(els.source.value) === source);
}

