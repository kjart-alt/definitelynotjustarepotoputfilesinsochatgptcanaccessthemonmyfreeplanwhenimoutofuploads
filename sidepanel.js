/**
 * Куда уходят устоявшиеся строки (автосохранение в графите). Устоявшаяся —
 * та, под которой лежат ещё две: feed правит только верхнюю и ту, что под ней
 * (растущую под снимком), глубже лента не меняется. Так каждая строка уходит в
 * журнал и файл ровно раз и уже в окончательном виде, а ленте хватает окна (KEEP).
 * null в sink — конец сеанса.
 */
let sink = null;
function settle(all = false) {
  if (!sink) return;
  const end = all ? cues.length : cues.length - 2;
  for (let i = 0; i < end; i++) {
    const c = cues[i];
    if (c.saved) continue;
    c.saved = true;
    sink(c);
  }
}
